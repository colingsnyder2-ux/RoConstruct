"""census-checks-snapshot.json: the census jobs of every prove-out run, newest per native source.

prove-out/OgreNativeFull/checks.json (the aggregate of all native sources) is regenerated by the recovery lane and is
missing for hours at a time. The per-run folders prove-out/*/checks.json hold the same jobs. layout_census falls back
to this snapshot when the aggregate is missing. Read-only on prove-out.

Run: python work/native-client/layout/build_census_snapshot.py
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
PROVE = HERE.parent / 'prove-out'
OUT = HERE / 'census-checks-snapshot.json'


def main():
    best = {}                                     # source -> (mtime, job)
    runs = 0
    for path in PROVE.glob('*/checks.json'):
        try:
            data = json.loads(path.read_text(encoding='utf-8'))
            mtime = path.stat().st_mtime
        except (OSError, ValueError):
            continue
        runs += 1
        for job in data.get('jobs', []):
            source = str(job.get('source', '')).replace('\\', '/').casefold()
            if source and (source not in best or mtime > best[source][0]):
                best[source] = (mtime, job)
    jobs = [job for _m, job in best.values()]
    OUT.write_text(json.dumps({'jobs': jobs}, separators=(',', ':')), encoding='utf-8')
    print('%d runs, %d sources, %d function checks' % (runs, len(jobs), sum(len(j.get('checks', [])) for j in jobs)))


if __name__ == '__main__':
    main()
