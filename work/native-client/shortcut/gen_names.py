"""Generate real definitions for the zeroed class-name globals (sX) the shortcut link used to stub.
The value of RBX's sFoo is the string "Foo" (reflection class/member names).  python gen_names.py"""
import json, re
from pathlib import Path
H = Path('work/native-client/shortcut')
un = json.load(open(H / 'unresolved12.json'))
groups = {'QBDB': [], 'PADA': []}
for s in un:
    m = re.match(r'^\?(s[A-Z]\w*)((?:@\w+)*)@@3(QBDB|PADA)$', s)
    if m:
        ns = [x for x in m.group(2).split('@') if x][::-1]
        groups[m.group(3)].append((m.group(1), ns))
for kind, rows in groups.items():
    out = ['// Shortcut glue (owner-authorized): reflection class/member name globals whose real values are the names themselves.',
           '// Generated by gen_names.py from the unresolved symbols of the stub-backed link (kind %s).' % kind]
    for name, ns in rows:
        val = name[1:]
        open_ = ''.join('namespace %s { ' % n for n in ns)
        close = '}' * len(ns)
        if kind == 'QBDB':
            out.append('%sextern const char* const %s; const char* const %s = "%s"; %s' % (open_, name, name, val, close))
        else:
            out.append('%schar* %s = (char*)"%s"; %s' % (open_, name, val, close))
    (H / ('NameGlobals_%s.cpp' % kind)).write_text('\n'.join(out) + '\n')
    print(kind, len(rows))
