"""Identical-COMDAT folding: the exe keeps one body for many symbols (e.g. every TToolVerb<...>::isChecked).  rename.py gives the
analog only the first name; alias every other still-undefined symbol bound to the same address.  Writes FoldAliasGlue.cpp.
python fold_aliases.py"""
import json, sys
from pathlib import Path
sys.path.insert(0, '.')
from roc.rebuild import coff_externals
H = Path('work/native-client/shortcut'); C = H / 'closure'
un = set(json.load(open(H / 'unresolved12.json')))
cb = json.load(open('work/native-client/claude-identity-closure-v5.json'))
addr = {x['symbol']: x['addr'] for x in cb['bindings'] if x.get('addr')}
if (C / 'helper_addrs.json').exists():
    for s, a in json.load(open(C / 'helper_addrs.json')).items():
        addr.setdefault(s, a)
res = json.load(open(C / 'rename.json'))
owner = {}
for a, r in res.items():
    o = C / 'renamed' / (a + '.obj')
    if r.get('status') == 'renamed' and o.exists() and r.get('symbol'):
        if r['symbol'] in {s for s, d in coff_externals(o.read_bytes()).items() if d}:
            owner[a] = r['symbol']
lines = []
for s in sorted(un):
    a = addr.get(s)
    if a in owner and owner[a] != s:
        lines.append('#pragma comment(linker, "/alternatename:%s=%s")' % (s, owner[a]))
(H / 'FoldAliasGlue.cpp').write_text('// Shortcut glue (owner-authorized), generated by fold_aliases.py: folded bodies shared by several symbols.\n' + '\n'.join(lines) + '\n')
print('aliases', len(lines))
