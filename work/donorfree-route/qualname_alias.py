"""python qualname_alias.py [STUBLIST...]: stubbed decorated names that are the same function as one defined symbol,
spelled differently by a draft: (1) only the access/virtual letter differs (?onChildAdded@DataModel@RBX@@MAEX.. vs UAEX..),
or (2) the differing part names a type no defined symbol uses (a draft's invented `String` for std::string:
?resolveMapPath@LDraw2Lua@RBX@@YA?AUString@@PBD@Z returned NULL from a stub). Same qualified name, unique candidate,
identical parameter tail. Writes aliases_qualname.txt. Seconds."""
import json, os, re, sys
from pathlib import Path
H = Path(__file__).parent
D = [d for d in json.load(open(H / 'renamed/defined.json')) if re.match(r'^\?(?:\?[01])?[A-Za-z_]', d)]
q = {}
for d in D:
    k = d.split('@@')[0]
    if '$' not in k:
        q.setdefault(k, set()).add(d)
used = set()
for d in D:
    used |= set(re.findall(r'[VU]([A-Za-z_]\w*)@', d))
_sj = json.load(open(H / 'link/stubs.json'))
stubs = set(_sj['functions']) | set(_sj.get('data', []))   # data too: cv-variant globals
for a in sys.argv[1:]:
    stubs |= set(Path(a).read_text().split())


def same(s, d):
    k = s.split('@@')[0]
    a, b = s[len(k) + 2:], d[len(k) + 2:]
    if a[1:] == b[1:]:
        return True                                       # access / virtual letter only
    if a[:1] == b[:1] and a[:1] in '23' and a[2:] == b[2:] and a[1:2] in 'PQRS' and b[1:2] in 'PQRS':
        return True                                       # data: pointer cv-qualifier only (ContentProvider* volatile)
    p = 0
    while p < min(len(a), len(b)) and a[p] == b[p]:
        p += 1
    x = 0
    while x < min(len(a), len(b)) - p and a[-1 - x] == b[-1 - x]:
        x += 1
    if x < 2:
        return False
    diff = a[p:len(a) - x]
    inv = [t for t in re.findall(r'[VU]([A-Za-z_]\w*)(?:@@|$)', diff) if t not in used]
    # a stand-in for a std type (draft struct String vs std::basic_string): global user type vs @std@@
    std_standin = bool(re.fullmatch(r'[VU][A-Za-z_]\w*(?:@@)?', diff)) and '@std@@' in b[p:len(b) - x]
    return bool(inv) or std_standin


out = {}
for s in stubs:
    if not re.match(r'^\?(?:\?[01])?[A-Za-z_]', s):
        continue
    k = s.split('@@')[0]
    if '$' in k:
        continue
    c = q.get(k, set()) - {s}
    if len(c) == 1:
        d = next(iter(c))
        if same(s, d):
            out[s] = d
# (3) same function name and identical signature, namespace path differs (::LDraw2Lua vs RBX::LDraw2Lua: a stub returned
#     no std::string and its destructor corrupted the heap in setAssetFolder)
sig = {}
for d in D:
    h, _, rest = d.partition('@@')
    if rest:
        sig.setdefault((h.split('@')[0], rest), set()).add(d)
for s in stubs:
    if s in out or not re.match(r'^\?(?:\?[01])?[A-Za-z_]', s):
        continue
    h, _, rest = s.partition('@@')
    c = sig.get((h.split('@')[0], rest), set()) - {s}
    if len(c) == 1:
        d = next(iter(c))
        hs, hd = h.split('@')[1:], d.partition('@@')[0].split('@')[1:]
        if hs and set(hs) <= set(hd):   # the stub's path is part of the real one (dropped namespace)
            out[s] = d
# (3) a member DECLARED in a native header with its address comment ('afx_msg void OnPaint(); // 0045eaa0') but defined
# nowhere natively: bind it to that address's converted exact function func_<addr> (CRobloxWnd message-map handlers)
_decl = {}
_cls = None
for _hf in (H.parents[1] / 'rebuild/2008-06/native-headers').rglob('*.h'):
    for _l in _hf.read_text(errors='replace').splitlines():
        _m = re.match(r'\s*(?:__declspec\([^)]*\)\)?\s*)?(?:class|struct)\s+(?:\w+\s+)?(\w+)\s*(?::[^;]*)?\{?\s*$', _l)
        if _m:
            _cls = _m.group(1)
        _m = re.match(r'\s*(?:afx_msg\s+|virtual\s+|static\s+)*[\w:<>\*& ]+?\b(~?\w+)\s*\([^;]*\)\s*(?:const\s*)?;\s*//\s*([0-9a-f]{8})\b', _l)
        if _m and _cls:
            _decl.setdefault((_m.group(1), _cls), set()).add(_m.group(2))
for s in stubs:
    if s in out:
        continue
    m = re.match(r'^\?(\w+)@(\w+)@@', s)
    if m and len(_decl.get((m.group(1), m.group(2)), ())) == 1:
        a = next(iter(_decl[(m.group(1), m.group(2))]))
        if (H / 'renamed/obj' / (a + '.obj')).exists():
            out[s] = 'func_' + a
(H / 'aliases_qualname.txt').write_text('# generated by qualname_alias.py\n' + ''.join('%s=%s\n' % kv for kv in sorted(out.items())))
print('%d stubbed names aliased to the same function under its real spelling' % len(out))
