"""python stdinst.py [--jobs N]: replace stubbed std:: template members (std::list/vector/_Tree/... instantiated on our
types: 11k of the 21k stubs, all returning 0) with REAL code: demangle each, write an explicit instantiation
(`template void std::list<WIN32_FIND_DATAA>::_Incsize(unsigned int);`), forward-declare the user types with the right
class/struct keyword, compile with the VS2008 compiler in parallel chunks, drop lines that fail, repeat until clean.
Objects: std_inst/*.obj, listed in extra/objs.txt (the link then defines those names and they are no longer stubbed).
Only names the object really defines count (checked against the stub list); same flags as the client (/O2 /MD /EHsc)."""
import json, os, re, subprocess, sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
H = Path(__file__).parent
ROOT = H.parents[1]
sys.path.insert(0, str(ROOT))
from roc import rebuild
OUT = H / 'std_inst'
OUT.mkdir(exist_ok=True)
UND = str(ROOT / 'tools/msvc800sp1/VC/bin/undname.exe')
JOBS = int(sys.argv[sys.argv.index('--jobs') + 1]) if '--jobs' in sys.argv else 12

stubs = json.load(open(H / 'link/stubs.json'))['functions']
want = [s for s in stubs if ('@std@@' in s or '@stdext@@' in s) and len(s) < 2000]

cf = H / 'link/undname_full.json'
try:
    dem = json.loads(cf.read_text())
except Exception:
    dem = {}
todo = [s for s in want if s not in dem]
for i in range(0, len(todo), 150):
    out = subprocess.run([UND] + todo[i:i + 150], capture_output=True, text=True).stdout
    for a, b in re.findall(r'Undecoration of :- "(.*)"\s*\nis :- "(.*)"', out):
        dem[a] = b
cf.write_text(json.dumps(dem))

TAG = re.compile(r'\b(?:class|struct|union|enum)\s+')
def line_for(d):
    """undname text -> explicit instantiation (None when not expressible)"""
    if "`" in d or "'" in d or '__ptr64' in d or 'operator new' in d or 'operator delete' in d:
        return None
    d = re.sub(r'^(?:public|private|protected):\s*', '', d)
    d = re.sub(r'\b(?:virtual|static)\s+', '', d)
    d = re.sub(r'\b__(?:thiscall|cdecl|stdcall|fastcall|clrcall)\s*', '', d)
    d = TAG.sub('', d)
    d = d.replace('(void)', '()')
    if not re.search(r'\)\s*(?:const)?\s*$', d):
        return None
    return 'template ' + d.strip() + ';'

decl = {}   # full type name -> keyword, from the demangled text
for s in want:
    for kw, name in re.findall(r'\b(class|struct|union)\s+([A-Za-z_][\w:]*)', dem.get(s, '')):
        if not name.startswith(('std::', 'stdext::', 'boost::')) and '<' not in name:
            decl.setdefault(name, kw)
def fwd():
    out = []
    for name, kw in sorted(decl.items()):
        parts = name.split('::')
        if any('::'.join(parts[:i]) in decl for i in range(1, len(parts))):
            continue   # nested in a class (Ogre::Font::X): not forward-declarable; such lines fail and are dropped
        if len(parts) == 1:
            out.append('%s %s;' % (kw, name))
        elif all(re.fullmatch(r'[A-Z]\w*|[a-z]\w*', p) for p in parts):   # namespace-qualified (nested classes fail and get dropped)
            out.append(' '.join('namespace %s {' % p for p in parts[:-1]) + ' %s %s; ' % (kw, parts[-1]) + '}' * (len(parts) - 1))
    return out
PRE = ['// generated by stdinst.py', '#define WIN32_LEAN_AND_MEAN', '#include <windows.h>',
       '#include <list>', '#include <vector>', '#include <map>', '#include <set>', '#include <deque>', '#include <string>',
       '#include <algorithm>', '#include <memory>', '#include <utility>', '#include <functional>', '#include <hash_map>',
       '#include <boost/shared_ptr.hpp>', '#include <boost/weak_ptr.hpp>', '#include <boost/function.hpp>']
lines = sorted({l for l in (line_for(dem[s]) for s in want if s in dem) if l})
# a forward-declared user type used BY VALUE as a template argument needs its full definition: those lines cannot compile here
_ut = sorted((n for n in decl if '::' not in n or n.split('::')[0] not in ('std', 'stdext', 'boost')), key=len, reverse=True)
_byval = re.compile(r'[<,]\s*(?:const\s+)?(%s)\s*(?=[,>])' % '|'.join(re.escape(n) for n in _ut)) if _ut else None
_n0 = len(lines)
lines = [l for l in lines if not (_byval and _byval.search(l))]
print('dropped %d lines that need a complete user type' % (_n0 - len(lines)))
print('stubbed std members %d, demangled %d, instantiation lines %d, forward decls %d' % (len(want), sum(1 for s in want if s in dem), len(lines), len(decl)))

FLAGS = ['/nologo', '/c', '/w', '/O2', '/Ob2', '/Oy', '/GF', '/GS-', '/EHsc', '/MD', '/DNDEBUG', '/D_MBCS',
         '/I' + str(ROOT / 'tools/rbxgs/Client/boost_1_34_1/src')]
TC = rebuild.toolchain(21022)
def build(k, body):
    """compile one chunk, dropping failing instantiation lines until it compiles (<= 12 rounds)"""
    fwds = fwd()
    for rnd in range(60):
        if not body:
            return k, 0
        src = OUT / ('inst_%03d.cpp' % k)
        head = PRE + fwds
        src.write_text('\n'.join(head + body) + '\n')
        code, log = rebuild.run(TC, 'cl', FLAGS + ['/Fo' + str(OUT / ('inst_%03d.obj' % k)), str(src)], OUT)
        if code == 0:
            return k, len(body)
        bad = set()
        for m in re.finditer(r'inst_%03d\.cpp\((\d+)\)' % k, log):
            n = int(m.group(1)) - len(head) - 1
            if 0 <= n < len(body):
                bad.add(n)
        if not bad:   # error only inside a forward declaration / prelude: drop the declarations that failed
            fl = {int(m.group(1)) - len(PRE) - 1 for m in re.finditer(r'inst_%03d\.cpp\((\d+)\)' % k, log)}
            fwds = [f for i, f in enumerate(fwds) if i not in fl]
            if not fl:
                return k, -1
            continue
        body = [l for i, l in enumerate(body) if i not in bad]
    return k, -1
CH = 250
chunks = [lines[i:i + CH] for i in range(0, len(lines), CH)]
with ThreadPoolExecutor(JOBS) as ex:
    res = list(ex.map(lambda a: build(*a), enumerate(chunks)))
ok = [k for k, n in res if n > 0]
print('chunks %d compiled %d, lines kept %d' % (len(chunks), len(ok), sum(n for k, n in res if n > 0)))
# which stubbed names the objects really define (mangling must match exactly)
sys.path.insert(0, str(H))
from roc.rebuild import coff_externals
defined = set()
for k in ok:
    o = OUT / ('inst_%03d.obj' % k)
    defined |= {n for n, d in coff_externals(o.read_bytes()).items() if d}
hit = defined & set(want)
print('stubbed std members now really defined: %d of %d' % (len(hit), len(want)))
objs = [str((OUT / ('inst_%03d.obj' % k)).resolve()) for k in ok]
ex_ = (H / 'extra/objs.txt').read_text().splitlines()
ex_ = [l for l in ex_ if 'std_inst' not in l] + objs
(H / 'extra/objs.txt').write_text('\n'.join(l for l in ex_ if l.strip()) + '\n')
(H / 'auto/stdinst.json').write_text(json.dumps({'defined': sorted(hit), 'objects': objs}))
