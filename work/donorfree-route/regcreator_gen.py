"""python regcreator_gen.py CLASS [CLASS...]: native FactoryProduct<T,D,sT>::creator registrations (the creator static,
its ??__E initializer and atexit, via getCreator() like FactoryProductCreators2008.cpp) for classes that
AbstractFactoryProduct<Instance>::create(name) cannot find: their only registration was a converted initializer keying
the creators map with another Name object (Seat, Hole, Sky, LocalScript... NULL in Insert Object). T and D come from
the class's ??_7Creator@?$FactoryProduct@... vtable name in the last map (undname). One source per class header;
compiled through native_check_runner. Prints the results.json to bind."""
import collections, json, re, subprocess, sys
from pathlib import Path
H = Path(__file__).parent
ROOT = H.parents[1]
HDR = ROOT / 'rebuild/2008-06/native-headers'
UND = ROOT / 'tools/vc2008rtm/Program Files/Microsoft Visual Studio 9.0/VC/bin/undname.exe'
RAK = '/I{headers}/../../../tools/rbxgs/Client/Network/raknet30/Source'
BS = chr(92)
want = set(sys.argv[1:])
vt = {}
for l in open(H / 'linkexp/qt.map', errors='replace'):
    p = l.split()
    if len(p) >= 4 and p[1].startswith('??_7Creator@?$FactoryProduct@'):
        m = re.search(r'\$1\?s(\w+)@', p[1])
        if m and m.group(1) in want:
            if '3PADA' in p[1] or m.group(1) not in vt:
                vt[m.group(1)] = p[1]
cls_hdr = {}
for h in sorted(HDR.rglob('*.h')):
    if any(x in h.parts for x in ('boundfunc-call3', 'creatable-n-params', 'nullable-class-name')):
        continue
    for m in re.finditer(r'^\s*class\s+(\w+)\s*(?::|\{)', h.read_text(errors='replace'), re.M):
        cls_hdr.setdefault(m.group(1), h.relative_to(HDR).as_posix())
BODY = '''namespace RBX {
 template<typename Class, typename DerivedClass, const char* ClassName>
 const Name& FactoryProduct<Class, DerivedClass, ClassName>::className() { return Name::declare<ClassName>(); }
 template<typename Class, typename DerivedClass, const char* ClassName>
 FactoryProduct<Class, DerivedClass, ClassName>::Creator::Creator() { getCreators()[&className()] = this; isConstructed = 666; }
 template<typename Class, typename DerivedClass, const char* ClassName>
 FactoryProduct<Class, DerivedClass, ClassName>::Creator::~Creator() { getCreators().erase(&className()); }
 template<typename Class, typename DerivedClass, const char* ClassName>
 boost::shared_ptr<Object> FactoryProduct<Class, DerivedClass, ClassName>::Creator::create() const { return Creatable<Instance>::create<Class>(); }
 template<typename Class, typename DerivedClass, const char* ClassName>
 const Name& FactoryProduct<Class, DerivedClass, ClassName>::Creator::getClassName() const { return className(); }
 template<typename Class, typename DerivedClass, const char* ClassName>
 const typename FactoryProduct<Class, DerivedClass, ClassName>::Creator FactoryProduct<Class, DerivedClass, ClassName>::creator;
}
'''
PAT = re.compile(r'FactoryProduct<(?:class|struct) ([\w:]+),(?:class|struct) ([\w:]+),&?(?:char const \* const |char \* const |char const \* |char \* |char )?([\w:]+)>::Creator')
inst = collections.defaultdict(list)
for c, n in sorted(vt.items()):
    d = subprocess.run([str(UND), n], capture_output=True, text=True).stdout
    m = PAT.search(d)
    if not m:
        print('undecoded', c); continue
    T, D, N = m.groups()
    h = cls_hdr.get(T.split('::')[-1])
    if not h:
        print('no header', T); continue
    inst[h].append('template const RBX::ICreator& RBX::FactoryProduct<%s, %s, %s>::getCreator();' % (T, D, N))
print('classes with a Creator vtable: %d of %d (%s)' % (len(vt), len(want), sorted(want - set(vt))))
jobs = []
for i, (h, lines) in enumerate(sorted(inst.items())):
    src = ROOT / ('work/native-client/stub-drafts/StubLive_RegCreator2_%02d.cpp' % i)
    src.write_text('// native-flags: /O2 /Ob2 /Oy /GF /GS- /EHsc /MD /D_AFXDLL /DNDEBUG /D_MBCS %s\n'
                   '// generated by work/donorfree-route/regcreator_gen.py\n#include "util/Object.h"\n#include "%s"\n%s\n%s\n'
                   % (RAK, h, BODY, '\n'.join(lines)))
    jobs.append({'source': str(src), 'checks': [], 'ranges': [], 'layouts': []})
man = ROOT / 'work/native-client/stub-drafts/StubLive_RegCreator2.json'
man.write_text(json.dumps({'compiler_build': 21022, 'compiler_variant': 'default', 'jobs': jobs}))
r = subprocess.run([sys.executable, str(ROOT / 'rebuild/2008-06/tests/native_check_runner.py'), 'run', str(man)], capture_output=True, text=True)
run = re.search(r'"results":"([^"]+)"', r.stdout)
resf = run.group(1).replace(BS + BS, BS) if run else None
rows = json.loads(Path(resf).read_text()) if resf else []
rows = rows if isinstance(rows, list) else rows.get('results', [])
for row in rows:
    if row.get('status') != 'complete':
        print('failed:', Path(row.get('source', '')).name, open(row['source']).read().split('\n')[3])
print('regcreator_gen: headers %d, ok %d' % (len(jobs), sum(1 for x in rows if x.get('status') == 'complete')))
print(resf)
