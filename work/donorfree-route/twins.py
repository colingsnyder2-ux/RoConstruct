"""python twins.py: stubbed func_<addr> whose original body is identical (masked) to another original function that already has
an exact converted object, and whose direct call targets are identical too (one level) -> alias func_<addr> to that
object's symbol (aliases_twins.txt). No compile; template instantiations over different pointer types are the usual case."""
import json, re
from pathlib import Path
import capstone, pefile
H = Path(__file__).parent
ROOT = H.parents[1]
oh = json.load(open(H / 'auto/orig_hash.json'))
R = json.load(open(H / 'renamed/rename.json'))
img = bytes(pefile.PE(str(ROOT / 'clients/2008-06/Roblox.exe')).get_memory_mapped_image())
md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)
def calls(a):
    out = []
    for i in md.disasm(img[a - 0x400000:a - 0x400000 + 0x2000], a):
        if i.mnemonic == 'call' and i.op_str.startswith('0x'):
            out.append('%08x' % int(i.op_str, 16))
        if i.mnemonic in ('ret', 'int3'):
            break
    return out
stub = json.load(open(H / 'link/stubs.json'))['functions']
by = {}
for a, x in oh.items():
    by.setdefault(x, []).append(a)
lines, n = [], 0
for s in stub:
    m = re.fullmatch(r'func_([0-9a-f]{8})', s)
    if not m or m.group(1) not in oh:
        continue
    a = m.group(1)
    ca = calls(int(a, 16))
    for b in by[oh[a]]:
        if b == a or R.get(b, {}).get('status') != 'renamed':
            continue
        cb = calls(int(b, 16))
        if len(ca) == len(cb) and all(x == y or (oh.get(x) and oh.get(x) == oh.get(y)) for x, y in zip(ca, cb)):
            lines.append('%s=%s' % (s, R[b]['symbol'])); n += 1
            break
(H / 'aliases_twins.txt').write_text('# generated by twins.py\n' + '\n'.join(lines) + '\n')
print('twin aliases: %d stubbed functions -> exact identical twins' % n)
