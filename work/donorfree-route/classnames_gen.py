"""python classnames_gen.py: class-name globals (?sPart@RBX@@3PADA, ?sMotor@RBX@@3PBDB ...) that our link left as stub
DATA (zero blocks): every such class was declared with the name "" -> one shared Name for Part/ServiceProvider/
ScriptContext/..., Part/Motor/Glue unfindable by name, Insert Object heap corruption. Defines each with its real text
(the original's bytes at the registry address when it names that global, else the identifier without its 's'), in the
spelling the link asks for: 3PADA char[], 3PBDB const char*, 3QBDB const char[] (not const char* const: same mangling, but native code uses the array, so Motor registered
garbage) (one source per spelling: the same
identifier cannot have two types in one TU). Compiled through native_check_runner; prints results.json to bind."""
import json, re, subprocess, sys
from pathlib import Path
import pefile
H = Path(__file__).parent
ROOT = H.parents[1]
BS = chr(92)
reg = json.load(open(ROOT / 'work/2008-06/identity-registry.json'))
byname = {}
for a, v in reg.items():
    n = (v or {}).get('name')
    if n:
        byname.setdefault(n, []).append(int(a, 16))
o = pefile.PE(str(ROOT / 'clients/2008-06/Roblox.exe'), fast_load=True).get_memory_mapped_image()
PAT = re.compile(r'^\?(s\w+)@((?:\w+@)*)@3(PADA|PBDB|QBDB)$')   # * : global-namespace names too (?sStockSound@@3PADA)
want = {'PADA': {}, 'PBDB': {}, 'QBDB': {}}
_force = json.load(open(H / 'auto/classname_force.json')) if (H / 'auto/classname_force.json').exists() else []   # names whose
# char[] <-> pointer alias quicktest now refuses: they need a real definition in this same cycle
_names = [l.split()[1] for l in open(H / 'linkexp/qt.map', errors='replace') if len(l.split()) >= 4 and 'stubs' in l.split()[-1]] + _force
_stf = H / 'auto/classnames_gen_names.json'   # grow-only (results swap keeps the newest object per source)
try:
    _names += [n for n in json.load(open(_stf)) if n not in _names]
except (OSError, ValueError):
    pass
json.dump(sorted({n for n in _names if PAT.match(n)}), open(_stf, 'w'))
for _nm in _names:
    p = [None, _nm]
    if True:
        m = PAT.match(p[1])
        if not m:
            continue
        var, ns = m.group(1), [x for x in m.group(2).split('@') if x]
        text = None
        for nm in (p[1], '?%s@%s@3PADA' % (var, m.group(2)), '?%s@%s@3QBDB' % (var, m.group(2)), '?%s@%s@3PBDB' % (var, m.group(2))):
            for A in byname.get(nm, []):
                raw = bytes(o[A - 0x400000:A - 0x400000 + 64])
                if nm.endswith(('PBDB', 'QBDB')) and not (raw[:1] and all(32 <= c < 127 for c in raw.split(b'\0')[0][:1])):   # pointer variable: follow it (3QBDB may be the array)
                    t = int.from_bytes(raw[:4], 'little')
                    raw = bytes(o[t - 0x400000:t - 0x400000 + 64]) if 0x400000 <= t < 0xa00000 else b''
                s = raw.split(b'\0')[0]
                if s and all(32 <= c < 127 for c in s):
                    text = s.decode(); break
            if text:
                break
        want[m.group(3)][(var, tuple(ns))] = text or var[1:]
jobs = []
TPL = {'PADA': '%s char %s[] = "%s";', 'PBDB': '%s const char* %s = "%s";', 'QBDB': '%s extern const char %s[] = "%s";'}
for sp, items in want.items():
    if not items:
        continue
    lines = []
    for (var, ns), text in sorted(items.items()):
        open_ = ' '.join('namespace %s {' % x for x in reversed(ns))
        lines.append(open_ + ' ' + (TPL[sp] % ('', var, text)).strip() + ' ' + '}' * len(ns))
    src = ROOT / ('work/native-client/stub-drafts/StubLive_ClassNames_%s.cpp' % sp)
    src.write_text('// native-flags: /O2 /GF /GS- /MD /DNDEBUG\n// generated by work/donorfree-route/classnames_gen.py\n' + '\n'.join(lines) + '\n')
    jobs.append({'source': str(src), 'checks': [], 'ranges': [], 'layouts': []})
man = ROOT / 'work/native-client/stub-drafts/StubLive_ClassNames.json'
man.write_text(json.dumps({'compiler_build': 21022, 'compiler_variant': 'default', 'jobs': jobs}))
r = subprocess.run([sys.executable, str(ROOT / 'rebuild/2008-06/tests/native_check_runner.py'), 'run', str(man)], capture_output=True, text=True)
run = re.search(r'"results":"([^"]+)"', r.stdout)
resf = run.group(1).replace(BS + BS, BS) if run else None
rows = json.loads(Path(resf).read_text()) if resf else []
rows = rows if isinstance(rows, list) else rows.get('results', [])
print('classnames_gen: stubbed class-name globals %s, sources ok %d/%d'
      % ({k: len(v) for k, v in want.items()}, sum(1 for x in rows if x.get('status') == 'complete'), len(jobs)))
print(resf)
