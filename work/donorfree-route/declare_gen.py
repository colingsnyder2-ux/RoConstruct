"""python declare_gen.py: stubbed Name::declare<sX>() / doDeclare<sX>() / callDoDeclare<sX>() (64 `return 0` stubs:
ClassDescriptor ctors got whatever eax held as their Name& -> 7 classes shared one garbage Name, Part/Motor/Glue were
unfindable in the class tree). Instantiates the native util/Name.h templates for every class-name global X in the
native char[] spelling (3PADA; `extern char sX[]` declared here), compiles through native_check_runner, and writes
aliases from the analog spellings (3PBDB/3QBDB) to the native ones into aliases_spell.txt (grow-only)."""
import json, re, subprocess, sys
from pathlib import Path
H = Path(__file__).parent
ROOT = H.parents[1]
sys.path.insert(0, str(ROOT))
from roc import rebuild as rb
BS = chr(92)
PAT = re.compile(r'^\?\?\$(declare|doDeclare|callDoDeclare)@\$1\?(s\w+)@((?:\w+@)*)@3([PQ][AB]D[AB])@Name@RBX@@')
stubs, want = [], {}
for l in open(H / 'linkexp/qt.map', errors='replace'):
    p = l.split()
    if len(p) >= 4 and 'stubs' in p[-1]:
        m = PAT.match(p[1])
        if m:
            stubs.append(p[1])
            ns = [x for x in m.group(3).split('@') if x]
            want[(m.group(2), tuple(ns))] = 1
_stf = H / 'auto/declare_gen_names.json'   # grow-only: the --results swap keeps only the newest object per source, so
try:                                         # every run re-emits every name an earlier run emitted (else its aliases -> stub)
    for _n in json.load(open(_stf)):
        m = PAT.match(_n)
        if m and _n not in stubs:
            stubs.append(_n)
            want[(m.group(2), tuple(x for x in m.group(3).split('@') if x))] = 1
except (OSError, ValueError):
    pass
json.dump(sorted(set(stubs)), open(_stf, 'w'))
lines, decl = [], []
for (s, ns), _ in sorted(want.items()):
    q = '::'.join(reversed(ns))
    decl.append('namespace %s { extern char %s[]; }' % (' { namespace '.join(reversed(ns)), s) + ' }' * (len(ns) - 1) if ns else 'extern char %s[];' % s)
    full = '%s::%s' % (q, s) if q else s
    lines.append('template const RBX::Name& RBX::Name::declare<%s>();' % full)
src = ROOT / 'work/native-client/stub-drafts/StubLive_NameDeclare.cpp'
src.write_text('// native-flags: /O2 /Ob2 /Oy /GF /GS- /EHsc /MD /D_AFXDLL /DNDEBUG /D_MBCS\n'
               '// generated by work/donorfree-route/declare_gen.py\n#include "util/Name.h"\n' + '\n'.join(decl) + '\n' + '\n'.join(lines) + '\n')
man = src.with_suffix('.json')
man.write_text(json.dumps({'compiler_build': 21022, 'compiler_variant': 'default', 'jobs': [{'source': str(src), 'checks': [], 'ranges': [], 'layouts': []}]}))
r = subprocess.run([sys.executable, str(ROOT / 'rebuild/2008-06/tests/native_check_runner.py'), 'run', str(man)], capture_output=True, text=True)
run = re.search(r'"results":"([^"]+)"', r.stdout)
resf = run.group(1).replace(BS + BS, BS) if run else None
rows = json.loads(Path(resf).read_text()) if resf else []
rows = rows if isinstance(rows, list) else rows.get('results', [])
defs = set()
for row in rows:
    if row.get('status') == 'complete' and row.get('object'):
        defs |= {k for k, v in rb.coff_externals(Path(row['object']).read_bytes()).items() if v}
    else:
        print('BUILD FAILED; see', resf)
spell = lambda s: re.sub(r'3[PQ][AB]D[AB]@Name@RBX@@', '3PADA@Name@RBX@@', s)
al = {s: spell(s) for s in stubs if s not in defs and spell(s) in defs}
old = {}
try:
    old = dict(l.strip().split('=', 1) for l in open(H / 'aliases_spell.txt') if '=' in l)
except OSError:
    pass
old.update(al)
(H / 'aliases_spell.txt').write_text(''.join('%s=%s\n' % kv for kv in sorted(old.items())))
print('declare_gen: stubbed declare-family %d, class names %d, defined directly %d, spelling aliases %d'
      % (len(stubs), len(want), sum(1 for s in stubs if s in defs), len(al)))
print(resf)
