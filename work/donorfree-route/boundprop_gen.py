"""python boundprop_gen.py: stubbed BoundProp<T,1>::BoundPropGetSet<C> constructors (the converted static initializers
call them out of line with the analog's `BoundProp*` spelling, PAV123@) -> explicit instantiations of the NATIVE classes
(`BoundProp&`, same ABI), one source per header (some native headers conflict together), compiled through
native_check_runner, plus aliases_boundprop.txt (pointer spelling = reference spelling). Unlinked, the GetSet kept a
null vtable and property access crashed (Sky::prop_SkyRt in CPropGrid on File->New). Prints the run's results.json."""
import json, re, subprocess, sys
from pathlib import Path
H = Path(__file__).parent
ROOT = H.parents[1]
sys.path.insert(0, str(ROOT))
from roc import rebuild as rb
HDR = ROOT / 'rebuild/2008-06/native-headers'
T = {'H': 'int', 'M': 'float', '_N': 'bool', 'N': 'double'}
BS = chr(92)
stubs = []
for l in open(H / 'linkexp/qt.map', errors='replace'):
    p = l.split()
    if len(p) >= 4 and p[1].startswith('??0?$BoundPropGetSet@') and 'stubs' in p[-1] and 'QAE@PAV123@' in p[1]:
        stubs.append(p[1])
cls_hdr = {}
for h in sorted(HDR.rglob('*.h')):
    if any(s in h.parts for s in ('boundfunc-call3', 'creatable-n-params', 'nullable-class-name')):
        continue
    for m in re.finditer(r'^\s*class\s+(\w+)\s*(?::|\{)', h.read_text(errors='replace'), re.M):
        cls_hdr.setdefault(m.group(1), h.relative_to(HDR).as_posix())


def demangle_type(s):   # V<Name>@<ns...>@@ or a builtin code
    if s in T:
        return T[s]
    m = re.fullmatch(r'V(\w+)@((?:\w+@)*)@', s)
    if m:
        ns = [x for x in m.group(2).split('@') if x]
        return '::'.join(list(reversed(ns)) + [m.group(1)])
    return None


PAT = re.compile(r'^\?\?0\?\$BoundPropGetSet@V(\w+)@((?:\w+@)*)@@\?\$BoundProp@(.+?)\$00@Reflection@RBX@@QAE@')
inst, alias = {}, []
for n in stubs:
    m = PAT.match(n)
    if not m:
        continue
    cls, ns = m.group(1), [x for x in m.group(2).split('@') if x]
    ty = demangle_type(m.group(3))
    if not ty or cls not in cls_hdr:
        print('skip', cls, m.group(3))
        continue
    cq = '::'.join(list(reversed(ns)) + [cls])
    inst.setdefault(cls_hdr[cls], []).append('template class RBX::Reflection::BoundProp<%s, 1>::BoundPropGetSet<%s>;' % (ty, cq))
    alias.append('%s=%s' % (n, n.replace('QAE@PAV123@', 'QAE@AAV123@')))
jobs = []
for i, (h, lines) in enumerate(sorted(inst.items())):
    src = ROOT / ('work/native-client/stub-drafts/StubLive_BoundProp_%02d.cpp' % i)
    src.write_text('// native-flags: /O2 /Ob2 /Oy /GF /GS- /EHsc /MD /D_AFXDLL /DNDEBUG /D_MBCS\n'
                   '// generated by work/donorfree-route/boundprop_gen.py\n'
                   '#include "util/Object.h"\n#include "%s"\n\n%s\n' % (h, '\n'.join(lines)))
    jobs.append({'source': str(src), 'checks': [], 'ranges': [], 'layouts': []})
man = ROOT / 'work/native-client/stub-drafts/StubLive_BoundProp.json'
man.write_text(json.dumps({'compiler_build': 21022, 'compiler_variant': 'default', 'jobs': jobs}))
r = subprocess.run([sys.executable, str(ROOT / 'rebuild/2008-06/tests/native_check_runner.py'), 'run', str(man)], capture_output=True, text=True)
run = re.search(r'"results":"([^"]+)"', r.stdout)
resf = run.group(1).replace(BS + BS, BS) if run else None
res = json.loads(Path(resf).read_text()) if resf else None
rows = (res if isinstance(res, list) else res['results']) if res else []
defs = set()
for row in rows:
    if row.get('status') == 'complete' and row.get('object'):
        defs |= {k for k, v in rb.coff_externals(Path(row['object']).read_bytes()).items() if v}
    else:
        print('failed:', Path(row.get('source', '')).name)
alias = [a for a in alias if a.split('=', 1)[1] in defs]
(H / 'aliases_boundprop.txt').write_text('\n'.join(alias) + '\n')
print('boundprop_gen: stubbed ctors %d, headers %d, aliased %d' % (len(stubs), len(inst), len(alias)))
print(resf)
