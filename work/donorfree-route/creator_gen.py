"""python creator_gen.py: FactoryProduct<T,D,N>::Creator members our link left as `return 0` stubs: Creator() (the
creators-map registration: Decal, Hint, Message, StringValue... never registered -> create(name) NULL), ~Creator(),
create() const (Part, Weld, Motor... -> NULL) and getClassName() const. Emits explicit instantiations of exactly the
stubbed members (never the `creator` statics: no second registration) from the native headers, one source per class
header, with the template bodies of FactoryProductCreators2008.cpp / AppUnit400_2008Creators.cpp; compiles them through
native_check_runner, then writes aliases from the analog spellings (3PBDB/3QBDB class-name globals) to the native
3PADA definitions into aliases_spell.txt (grow-only). Prints the results.json to bind with quicktest --results."""
import collections, json, re, subprocess, sys
from pathlib import Path
H = Path(__file__).parent
ROOT = H.parents[1]
sys.path.insert(0, str(ROOT))
from roc import rebuild as rb
HDR = ROOT / 'rebuild/2008-06/native-headers'
UND = ROOT / 'tools/vc2008rtm/Program Files/Microsoft Visual Studio 9.0/VC/bin/undname.exe'
BS = chr(92)
MEMBERS = {'?create@Creator@': 'template boost::shared_ptr<RBX::Object> RBX::FactoryProduct<%s, %s, %s>::Creator::create() const;',
           '??0Creator@': 'template RBX::FactoryProduct<%s, %s, %s>::Creator::Creator();',
           '??1Creator@': 'template RBX::FactoryProduct<%s, %s, %s>::Creator::~Creator();',
           '?getClassName@Creator@': 'template const RBX::Name& RBX::FactoryProduct<%s, %s, %s>::Creator::getClassName() const;'}
stubs = []
for l in open(H / 'linkexp/qt.map', errors='replace'):
    p = l.split()
    if len(p) >= 4 and 'stubs' in p[-1] and any(p[1].startswith(k + '?$FactoryProduct@') for k in MEMBERS):
        stubs.append(p[1])
cls_hdr = {}
for h in sorted(HDR.rglob('*.h')):
    if any(s in h.parts for s in ('boundfunc-call3', 'creatable-n-params', 'nullable-class-name')):
        continue
    for m in re.finditer(r'^\s*class\s+(\w+)\s*(?::|\{)', h.read_text(errors='replace'), re.M):
        cls_hdr.setdefault(m.group(1), h.relative_to(HDR).as_posix())
BODY = '''namespace RBX {
 template<typename Class, typename DerivedClass, const char* ClassName>
 const Name& FactoryProduct<Class, DerivedClass, ClassName>::className() { return Name::declare<ClassName>(); }
 template<typename Class, typename DerivedClass, const char* ClassName>
 FactoryProduct<Class, DerivedClass, ClassName>::Creator::Creator() { getCreators()[&className()] = this; isConstructed = 666; }
 template<typename Class, typename DerivedClass, const char* ClassName>
 FactoryProduct<Class, DerivedClass, ClassName>::Creator::~Creator() { getCreators().erase(&className()); }
 template<typename Class, typename DerivedClass, const char* ClassName>
 boost::shared_ptr<Object> FactoryProduct<Class, DerivedClass, ClassName>::Creator::create() const { return Creatable<Instance>::create<Class>(); }
 template<typename Class, typename DerivedClass, const char* ClassName>
 const Name& FactoryProduct<Class, DerivedClass, ClassName>::Creator::getClassName() const { return className(); }
}
'''
PAT = re.compile(r'FactoryProduct<(?:class|struct) ([\w:]+),(?:class|struct) ([\w:]+),&?(?:char const \* const |char \* const |char const \* |char \* |char )?([\w:]+)>::Creator::')
inst = collections.defaultdict(set)
for n in stubs:
    d = subprocess.run([str(UND), n], capture_output=True, text=True).stdout
    m = PAT.search(d)
    if not m:
        print('undecoded', n[:90]); continue
    T, D, N = m.groups()
    h = cls_hdr.get(T.split('::')[-1])
    if not h:
        print('no header for', T); continue
    key = next(k for k in MEMBERS if n.startswith(k + '?$FactoryProduct@'))
    inst[h].add(MEMBERS[key] % (T, D, N))
jobs = []
for i, (h, lines) in enumerate(sorted(inst.items())):
    src = ROOT / ('work/native-client/stub-drafts/StubLive_Creator_%02d.cpp' % i)
    src.write_text('// native-flags: /O2 /Ob2 /Oy /GF /GS- /EHsc /MD /D_AFXDLL /DNDEBUG /D_MBCS\n'
                   '// generated by work/donorfree-route/creator_gen.py\n#include "util/Object.h"\n#include "%s"\n%s\n%s\n'
                   % (h, BODY, '\n'.join(sorted(lines))))
    jobs.append({'source': str(src), 'checks': [], 'ranges': [], 'layouts': []})
man = ROOT / 'work/native-client/stub-drafts/StubLive_Creator.json'
man.write_text(json.dumps({'compiler_build': 21022, 'compiler_variant': 'default', 'jobs': jobs}))
r = subprocess.run([sys.executable, str(ROOT / 'rebuild/2008-06/tests/native_check_runner.py'), 'run', str(man)], capture_output=True, text=True)
run = re.search(r'"results":"([^"]+)"', r.stdout)
resf = run.group(1).replace(BS + BS, BS) if run else None
res = json.loads(Path(resf).read_text()) if resf else None
rows = (res if isinstance(res, list) else res['results']) if res else []
defs = set()
for row in rows:
    if row.get('status') == 'complete' and row.get('object'):
        defs |= {k for k, v in rb.coff_externals(Path(row['object']).read_bytes()).items() if v}
    else:
        print('failed:', Path(row.get('source', '')).name, open(row['source'], errors='replace').read().split('\n')[3][:70])
spell = lambda s: re.sub(r'3[PQ][AB]D[AB]@RBX@@', '3PADA@RBX@@', s)
al = {s: spell(s) for s in stubs if s not in defs and spell(s) in defs}
old = {}
try:
    old = dict(l.strip().split('=', 1) for l in open(H / 'aliases_spell.txt') if '=' in l)
except OSError:
    pass
old.update(al)
(H / 'aliases_spell.txt').write_text(''.join('%s=%s\n' % kv for kv in sorted(old.items())))
print('creator_gen: stubbed Creator members %d, headers %d, defined directly %d, aliased spellings %d'
      % (len(stubs), len(inst), sum(1 for s in stubs if s in defs), len(al)))
print(resf)
