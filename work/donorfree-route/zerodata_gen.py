"""python zerodata_gen.py: dat_<A> placeholders our link left as ZERO data while the original holds a string literal there
("url", "BMP", "min", "LocalScript", "Closing log file" ...: data_zero_audit). Code comparing or printing them saw "".
Census: every dat_ symbol in a stubs object whose bytes in run/RobloxQT.exe are all zero while the original's bytes at A
are a printable NUL-terminated string -> `extern "C" const char Zs_<A>[] = "<text>";` compiled through native_check_runner
and aliased dat_<A>=_Zs_<A> in aliases_zerodata.txt (grow-only; the alias keeps the name from being stubbed)."""
import json, re, subprocess, sys
from pathlib import Path
import pefile
H = Path(__file__).parent
ROOT = H.parents[1]
BS = chr(92)
o = pefile.PE(str(ROOT / 'clients/2008-06/Roblox.exe'), fast_load=True)
oi, ob = bytes(o.get_memory_mapped_image()), 0x400000
q = pefile.PE(str(H / 'run/RobloxQT.exe'), fast_load=True)
qi, qb = bytes(q.get_memory_mapped_image()), q.OPTIONAL_HEADER.ImageBase
want = {}
for l in open(H / 'linkexp/qt.map', errors='replace'):
    p = l.split()
    if len(p) < 4 or ':' not in p[0] or 'stubs' not in p[-1] or not re.fullmatch(r'dat_[0-9a-f]{8}', p[1]):
        continue
    a, va = int(p[1][4:], 16), int(p[2], 16)
    if not (ob <= a < ob + len(oi)) or not (qb <= va < qb + len(qi)):
        continue
    raw = oi[a - ob:a - ob + 512]
    z = raw.find(b'\0')
    if z < 1 or not all(32 <= c < 127 or c in (9, 10, 13) for c in raw[:z]):
        continue
    if any(qi[va - qb:va - qb + min(z + 1, 16)]):
        continue   # our copy is not zero
    want[p[1][4:]] = raw[:z].decode('latin-1')
_stf = H / 'auto/zerodata_state.json'   # grow-only: the --results swap keeps only the newest object per source
try:
    for a_, t_ in json.load(open(_stf)).items():
        want.setdefault(a_, t_)
except (OSError, ValueError):
    pass
try:   # seed from aliases_zerodata.txt (dat_<A>=_Zs_<A>): the original's string at A
    for l_ in open(H / 'aliases_zerodata.txt'):
        if '=_Zs_' in l_:
            a_ = l_.split('=_Zs_')[1].strip()
            if a_ not in want:
                raw_ = oi[int(a_, 16) - ob:int(a_, 16) - ob + 512]; want[a_] = raw_[:raw_.find(b'\0')].decode('latin-1')
except OSError:
    pass
json.dump(want, open(_stf, 'w'))
esc = lambda s: s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n').replace('\r', '\\r').replace('\t', '\\t').replace('?', '\\?')
src = ROOT / 'work/native-client/stub-drafts/StubLive_ZeroData.cpp'
src.write_text('// native-flags: /O2 /GS- /MD /DNDEBUG\n// generated by work/donorfree-route/zerodata_gen.py: original string literals at zero-stubbed dat_ addresses\n'
               + ''.join('extern "C" const char Zs_%s[] = "%s";\n' % (a, esc(t)) for a, t in sorted(want.items())))
man = src.with_suffix('.json')
man.write_text(json.dumps({'compiler_build': 21022, 'compiler_variant': 'default', 'jobs': [{'source': str(src), 'checks': [], 'ranges': [], 'layouts': []}]}))
r = subprocess.run([sys.executable, str(ROOT / 'rebuild/2008-06/tests/native_check_runner.py'), 'run', str(man)], capture_output=True, text=True)
run = re.search(r'"results":"([^"]+)"', r.stdout)
resf = run.group(1).replace(BS + BS, BS) if run else None
rows = json.loads(Path(resf).read_text()) if resf else []
rows = rows if isinstance(rows, list) else rows.get('results', [])
if any(x.get('status') == 'complete' for x in rows):
    old = {}
    try:
        old = dict(l.strip().split('=', 1) for l in open(H / 'aliases_zerodata.txt') if '=' in l)
    except OSError:
        pass
    old.update({'dat_' + a: '_Zs_' + a for a in want})
    (H / 'aliases_zerodata.txt').write_text(''.join('%s=%s\n' % kv for kv in sorted(old.items())))
else:
    print('BUILD FAILED; see', resf)
print('zerodata_gen: zero-stubbed original strings %d (e.g. %s)' % (len(want), list(want.values())[:6]))
print(resf)
