"""python facprod_gen.py: stubbed func_<X> that are really FactoryProduct<T,D,N>::FactoryProduct() (the original body
calls the base constructor, then stores FactoryProduct<T..> vtables; registry names of these ICF bodies lie:
004a15f0 'ScriptContext::ScriptContext' is FactoryProduct<Server,Peer,sServer>). Their stubs left Server/Client
half-built (null rakPeer) when Insert Object probed them. Builds each from the native headers (empty template
constructor definition: the header only declares it), one source per class header, through native_check_runner, and
writes aliases_override.txt entries func_<X> = ??0?$FactoryProduct@...@IAE@XZ (override: their keys sit in
alias_zero.json). Prints the results.json to bind."""
import collections, json, re, subprocess, sys
from pathlib import Path
import capstone, pefile
H = Path(__file__).parent
ROOT = H.parents[1]
sys.path.insert(0, str(ROOT))
from roc import rebuild as rb
HDR = ROOT / 'rebuild/2008-06/native-headers'
UND = ROOT / 'tools/vc2008rtm/Program Files/Microsoft Visual Studio 9.0/VC/bin/undname.exe'
RAK = '/I{headers}/../../../tools/rbxgs/Client/Network/raknet30/Source'
BS = chr(92)
reg = json.load(open(ROOT / 'work/2008-06/identity-registry.json'))
o = pefile.PE(str(ROOT / 'clients/2008-06/Roblox.exe'), fast_load=True).get_memory_mapped_image()
md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)
stubs = set()
for l in open(H / 'linkexp/qt.map', errors='replace'):
    p = l.split()
    if len(p) >= 4 and 'stubs' in p[-1] and re.fullmatch(r'func_[0-9a-f]{8}', p[1]):
        stubs.add(p[1])
found = {}
for s in sorted(stubs):
    A = int(s[5:], 16)
    if not 0x401000 <= A < 0x7c0000:
        continue
    for i in md.disasm(bytes(o[A - 0x400000:A - 0x400000 + 0x40]), A):
        m = re.match(r'dword ptr \[e(?:si|ax|cx|di)\], 0x([0-9a-f]+)$', i.op_str) if i.mnemonic == 'mov' else None
        if m:
            vn = (reg.get('%08x' % int(m.group(1), 16)) or {}).get('name') or ''
            mv = re.match(r'^\?\?_7(\?\$FactoryProduct@.+?@RBX@@)6B', vn)
            if mv:
                found[s] = '??0' + mv.group(1) + 'IAE@XZ'
            break
        if i.mnemonic == 'ret':
            break
cls_hdr = {}
for h in sorted(HDR.rglob('*.h')):
    if any(x in h.parts for x in ('boundfunc-call3', 'creatable-n-params', 'nullable-class-name')):
        continue
    for m in re.finditer(r'^\s*class\s+(\w+)\s*(?::|\{)', h.read_text(errors='replace'), re.M):
        cls_hdr.setdefault(m.group(1), h.relative_to(HDR).as_posix())
BODY = ('namespace RBX { template<typename Class, typename DerivedClass, const char* ClassName>\n'
        ' FactoryProduct<Class, DerivedClass, ClassName>::FactoryProduct() {} }\n')
PAT = re.compile(r'FactoryProduct<(?:class|struct) ([\w:]+),(?:class|struct) ([\w:]+),&?(?:char const \* const |char \* const |char const \* |char \* |char )?([\w:]+)>::FactoryProduct')
inst = collections.defaultdict(set)
for s, ctor in found.items():
    d = subprocess.run([str(UND), ctor], capture_output=True, text=True).stdout
    m = PAT.search(d)
    if not m:
        print('undecoded', ctor[:90]); continue
    T, D, N = m.groups()
    h = cls_hdr.get(T.split('::')[-1])
    if not h:
        print('no header for', T); continue
    inst[h].add('template RBX::FactoryProduct<%s, %s, %s>::FactoryProduct();' % (T, D, N))
jobs = []
for i, (h, lines) in enumerate(sorted(inst.items())):
    src = ROOT / ('work/native-client/stub-drafts/StubLive_FacProd_%02d.cpp' % i)
    src.write_text('// native-flags: /O2 /Ob2 /Oy /GF /GS- /EHsc /MD /D_AFXDLL /DNDEBUG /D_MBCS %s\n'
                   '// generated by work/donorfree-route/facprod_gen.py\n#include "util/Object.h"\n#include "%s"\n%s\n%s\n'
                   % (RAK, h, BODY, '\n'.join(sorted(lines))))
    jobs.append({'source': str(src), 'checks': [], 'ranges': [], 'layouts': []})
man = ROOT / 'work/native-client/stub-drafts/StubLive_FacProd.json'
man.write_text(json.dumps({'compiler_build': 21022, 'compiler_variant': 'default', 'jobs': jobs}))
r = subprocess.run([sys.executable, str(ROOT / 'rebuild/2008-06/tests/native_check_runner.py'), 'run', str(man)], capture_output=True, text=True)
run = re.search(r'"results":"([^"]+)"', r.stdout)
resf = run.group(1).replace(BS + BS, BS) if run else None
res = json.loads(Path(resf).read_text()) if resf else None
rows = (res if isinstance(res, list) else res['results']) if res else []
defs = set()
for row in rows:
    if row.get('status') == 'complete' and row.get('object'):
        defs |= {k for k, v in rb.coff_externals(Path(row['object']).read_bytes()).items() if v}
    else:
        print('failed:', Path(row.get('source', '')).name)
al = {s: c for s, c in found.items() if c in defs}
old = {}
try:
    old = dict(l.strip().split('=', 1) for l in open(H / 'aliases_override.txt') if '=' in l)
except OSError:
    pass
old.update(al)
(H / 'aliases_override.txt').write_text(''.join('%s=%s\n' % kv for kv in sorted(old.items())))
print('facprod_gen: stubbed FactoryProduct ctors %d, headers %d, built+aliased %d' % (len(found), len(inst), len(al)))
print(resf)
