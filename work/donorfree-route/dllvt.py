"""python dllvt.py: exe-local copies of rgmain.dll vtables / RTTI / const data that our link only has as jmp THUNKS.
Analog TUs and native Ogre drafts were compiled without dllimport, so `mov [ecx], offset ??_7X@Ogre@@6B@` stored a
thunk address as the vptr (gemini dll_data_audit.json: 150 vtables/RTTI + const statics). For each such name:
linkexp/dllvt.obj gets writable storage (the DLL item plus the 4 bytes before it: a vtable's RTTI locator) with the
symbol defined at +4, and work/native-client/stub-drafts/DllVtCopy.cpp copies the DLL's bytes in at
#pragma init_seg(lib) (before any user static initializer). Contents are the DLL's, so virtual calls and RTTI behave the
same. Mutable statics (maps, dictionaries, counters) are NOT copied: a snapshot would split shared state.
Size = distance to the next rgmain export (<= 0x200). Prints the results path bindsrc bound."""
import bisect, json, re, struct, subprocess, sys
from pathlib import Path
import pefile
H = Path(__file__).parent
ROOT = H.parents[1]
dll = pefile.PE(str(H / 'run/rgmain.dll'))
exp = {e.name.decode('latin-1'): e.address for e in dll.DIRECTORY_ENTRY_EXPORT.symbols if e.name}
rvas = sorted(set(exp.values()))
names = []
defined = set()
for l in open(H / 'linkexp/qt.map', errors='replace'):
    p = l.split()
    if len(p) >= 4 and ':' in p[0]:
        if p[0].startswith('0001:') and p[-1] == 'rgmain:rgmain.dll':
            names.append(p[1])
        elif p[-1] != 'rgmain:rgmain.dll':
            defined.add(p[1])
local_ok = set((H / 'auto/dllvt_skip.txt').read_text().split()) if (H / 'auto/dllvt_skip.txt').exists() else set()
pick = []
for n in sorted(set(names)):
    if n in defined or n in local_ok or n not in exp:
        continue
    vt = n.startswith(('??_7', '??_R'))
    const = re.match(r'^\?[A-Za-z_]\w*(@\w+)*@@[0-3].*B$', n)
    if not vt:   # const statics: OgreConstImports.cpp builds them properly (would duplicate)
        continue
    r = exp[n]
    j = bisect.bisect_right(rvas, r)
    size = min((rvas[j] - r) if j < len(rvas) else 0x40, 0x200)
    pick.append((n, 4 if n.startswith('??_7') else 0, max(size, 4)))
# data object: one .data section, blob symbol at 0, each name at its offset (+4 for vtables)
blob, syms, table, off = bytearray(), [], [], 0
for n, pre, size in pick:
    syms.append((n, off + pre)); table.append((n, off, pre, size)); off += pre + size
    off = (off + 3) & ~3
blob = bytes(off)
strtab = bytearray()
def symrec(name, val, sec, cls):
    global strtab
    b = name.encode('latin-1')
    nm = b.ljust(8, b'\0') if len(b) <= 8 else struct.pack('<II', 0, 4 + len(strtab))
    if len(b) > 8:
        strtab += b + b'\0'
    return nm + struct.pack('<IhHBB', val, sec, 0, cls, 0)
st = symrec('_roc_dllvt_blob', 0, 1, 2) + b''.join(symrec(n, v, 1, 2) for n, v in syms)
raw_ptr = 20 + 40
hdr = struct.pack('<HHIIIHH', 0x14c, 1, 0, raw_ptr + len(blob), 1 + len(syms), 0, 0)
sec = b'.data\0\0\0' + struct.pack('<IIIIIIHHI', 0, 0, len(blob), raw_ptr, 0, 0, 0, 0, 0xC0300040)
(H / 'linkexp/dllvt.obj').write_bytes(hdr + sec + blob + st + struct.pack('<I', 4 + len(strtab)) + bytes(strtab))
src = ['// native-flags: /O2 /Ob2 /Oy /GF /GS- /EHsc /MD /D_AFXDLL /DNDEBUG /D_MBCS',
       '// generated by work/donorfree-route/dllvt.py: fill linkexp/dllvt.obj with the DLL\'s vtables / RTTI / const data',
       '#include <windows.h>', '#include <string.h>', '#pragma init_seg(lib)',
       'extern "C" char roc_dllvt_blob[];',
       'namespace {', 'struct Item { const char* name; unsigned off, pre, size; };', 'const Item items[] = {']
src += ['    { "%s", %d, %d, %d },' % (n, o, p, s) for n, o, p, s in table]
src += ['};', 'struct Fill { Fill() {',
        '    HMODULE h = GetModuleHandleA("rgmain.dll");',
        '    for (unsigned i = 0; h && i < sizeof(items) / sizeof(items[0]); ++i) {',
        '        const char* p = (const char*)GetProcAddress(h, items[i].name);',
        '        if (p) memcpy(roc_dllvt_blob + items[i].off, p - items[i].pre, items[i].pre + items[i].size);',
        '    } } } fill;', '}']
out = ROOT / 'work/native-client/stub-drafts/DllVtCopy.cpp'
out.write_text('\n'.join(src) + '\n')
r = subprocess.run([sys.executable, str(H / 'bindsrc.py'), str(out)], capture_output=True, text=True)
print(r.stdout.strip()[-200:], r.stderr.strip()[-400:])
print('dllvt: local copies of rgmain vtables/RTTI/const data: %d (%d bytes)' % (len(pick), len(blob)))
