"""python stdinst2.py [--jobs N]: phase 2 of stdinst.py: stubbed std:: members whose template arguments are user types BY
VALUE (std::vector<RBX::Foo>) need the full type: include the native header that defines it (index of class/struct
definitions in rebuild/2008-06/native-headers), compile with the native runner's flags, drop lines/headers that fail.
Objects std_inst/v_*.obj, appended to extra/objs.txt."""
import json, os, re, sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
H = Path(__file__).resolve().parent.parent
ROOT = H.parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / 'rebuild/2008-06/tests'))
from roc import rebuild
import native_check_runner as NCR
OUT = H / 'auto/stub_inst'
NH = ROOT / 'rebuild/2008-06/native-headers'
JOBS = int(sys.argv[sys.argv.index('--jobs') + 1]) if '--jobs' in sys.argv else 12
dem = json.loads((H / 'auto/stub_inst/undname.json').read_text())
stubs = json.load(open(H / 'auto/real_stubs.json'))
have = set(json.loads((H / 'auto/stub_inst.json').read_text())['defined'])
want = [s for s in stubs if s.startswith('?') and ('@std@@' in s or '@stdext@@' in s or '@boost@@' in s) and s not in have and s in dem]
exec(open(H / 'auto/stub_stdinst.py').read().split('decl = {}')[0].split('TAG = re.compile')[1].join(['TAG = re.compile', '']))  # line_for()
# header index: short type name -> [(namespace guess, header path relative to native-headers)]
idx = {}
for p in NH.rglob('*.h'):
    try:
        t = p.read_text(errors='replace')
    except OSError:
        continue
    ns = re.findall(r'^\s*namespace\s+(\w+)', t, re.M)
    for m in re.finditer(r'^\s*(?:class|struct)\s+(?:__declspec\([^)]*\)\s+)?(\w+)\s*(?::[^;{]*)?\{', t, re.M):
        idx.setdefault(m.group(1), []).append((ns, p.relative_to(NH).as_posix()))
def header_for(full):
    parts = full.split('::')
    cands = idx.get(parts[-1], [])
    for ns, h in cands:
        if all(x in ns for x in parts[:-1]):
            return h
    return cands[0][1] if cands else None
TY = re.compile(r'\b(?:class|struct)\s+([A-Za-z_][\w:]*)')
rows = []
for s in want:
    l = line_for(dem[s])
    if not l:
        continue
    hs = set()
    ok = True
    for t in set(TY.findall(dem[s])):
        if t.startswith(('std::', 'stdext::', 'boost::')):
            continue
        h = header_for(t)
        if h:
            hs.add(h)
    rows.append((tuple(sorted(hs)), l))
rows.sort()
print('value-type members %d, expressible %d, with all headers found %d' % (len(want), len(rows), sum(1 for h, l in rows if h)))
PRE = ['// native-flags: /O2 /Ob2 /Oy /GF /GS- /EHsc /MD /D_AFXDLL /DNDEBUG /D_MBCS', '// generated by stdinst2.py',
       '#include <afx.h>', '#include <list>', '#include <vector>', '#include <map>', '#include <set>', '#include <deque>',
       '#include <string>', '#include <algorithm>', '#include <hash_map>']
TC = rebuild.toolchain(21022)
def build(k, chunk):
    heads = sorted({h for hs, l in chunk for h in hs})
    body = [l for hs, l in chunk]
    for rnd in range(60):
        if not body:
            return k, 0
        src = OUT / ('v_%03d.cpp' % k)
        head = PRE + ['#include "%s"' % h for h in heads]
        src.write_text('\n'.join(head + body) + '\n')
        flags = NCR.compiler_flags(src)
        code, log = rebuild.run(TC, 'cl', flags + ['/w', '/Fo' + str(OUT / ('v_%03d.obj' % k)), str(src)], OUT)
        if code == 0:
            return k, len(body)
        bad = {int(m.group(1)) - len(head) - 1 for m in re.finditer(r'v_%03d\.cpp\((\d+)\)' % k, log)}
        bad = {b for b in bad if 0 <= b < len(body)}
        if bad:
            body = [l for i, l in enumerate(body) if i not in bad]
            continue
        # errors inside an included header: drop that header and every line that needed it
        hb = {h for h in heads if h.split('/')[-1] in log}
        if not hb:
            return k, -1
        heads = [h for h in heads if h not in hb]
        keep = {l for hs, l in chunk if not set(hs) & hb}
        body = [l for l in body if l in keep]
    return k, -1
CH = 120
chunks = [rows[i:i + CH] for i in range(0, len(rows), CH)]
with ThreadPoolExecutor(JOBS) as ex:
    res = list(ex.map(lambda a: build(*a), enumerate(chunks)))
ok = [k for k, n in res if n > 0]
from roc.rebuild import coff_externals
defined = set()
for k in ok:
    defined |= {n for n, d in coff_externals((OUT / ('v_%03d.obj' % k)).read_bytes()).items() if d}
hit = defined & set(want)
print('chunks %d compiled %d | value-type std members now defined: %d of %d' % (len(chunks), len(ok), len(hit), len(want)))
objs = [str((OUT / ('v_%03d.obj' % k)).resolve()) for k in ok]
d = json.loads((H / 'auto/stub_inst.json').read_text())
d['defined_v'] = sorted(hit); d['objects_v'] = objs
(H / 'auto/stub_inst.json').write_text(json.dumps(d))
print('done')
