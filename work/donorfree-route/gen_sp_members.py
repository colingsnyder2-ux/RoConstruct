"""python gen_sp_members.py: generate native-classes/ServiceProviderMembersBoot2008.cpp from the stub list: member
ServiceProvider::find<T>() const / create<T>() const instances (bodies as AppUnit448_2008Services.cpp). Prints skipped ones."""
import json, re, subprocess, glob, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
UN = str(ROOT / 'tools/msvc800sp1/VC/bin/undname.exe')
stubs = json.load(open(ROOT / 'work/donorfree-route/link/stubs.json'))['functions']
want = []
for s in stubs:
    m = re.match(r'^\?\?\$(find|create)@(.+)@@@ServiceProvider@RBX@@QBE', s)
    if not m: continue
    out = subprocess.run([UN, s], capture_output=True, text=True).stdout
    t = re.search(r'is :- "(.*)"', out)
    if not t: continue
    ty = re.search(r'ServiceProvider::(?:find|create)<class ([A-Za-z0-9_:]+)>', t.group(1))
    if ty: want.append((m.group(1), ty.group(1)))
hdr = {}
for h in glob.glob(str(ROOT / 'rebuild/2008-06/native-headers/**/*.h'), recursive=True):
    hp = h.replace(chr(92), '/'); rel = hp.split('native-headers/')[1]
    if any(x in rel for x in ('profile', 'inline', 'writer', 'mfc', 'std-', 'pv-parent', 'kernel-stages', 'engine-world', '/ViewNew/')): continue
    try: t = open(h, errors='ignore').read()
    except Exception: continue
    for m in re.finditer(r'\b(?:class|struct)\s+(?:__declspec\(novtable\)\s+)?([A-Za-z0-9_]+)\s*(?::|\{)', t):
        hdr.setdefault(m.group(1), []).append(rel)
inc, lines, skipped = set(), [], []
for kind, ty in sorted(set(want)):
    name = ty.split('::')[-1].replace('RBX::', '')
    if ty in ('RBX::Network::Client',): skipped.append(ty + ' (header needs RakNet includes)'); continue
    cands = hdr.get(name, [])
    if not cands: skipped.append(ty); continue
    inc.add(cands[0])
    lines.append('\ttemplate %s* ServiceProvider::%s<%s>() const;' % (ty.replace('RBX::', ''), kind, ty.replace('RBX::', '')))
body = open(ROOT / 'rebuild/2008-06/native-classes/AppUnit448_2008Services.cpp').read()
defs = body[body.index('\ttemplate<class Class> size_t ServiceProvider::getClassIndex'):body.index('\ttemplate ChangeHistoryService* ServiceProvider::find<ChangeHistoryService>() const;')]
defs = '\ttemplate<class Class> size_t ServiceProvider::doGetClassIndex() { static size_t index = newIndex(); return index; }\n\ttemplate<class Class> void ServiceProvider::callDoGetClassIndex() { doGetClassIndex<Class>(); }\n' + defs
src = ['// native-flags: /O2 /Ob2 /Oy /GF /GS- /EHsc /MD /D_AFXDLL /DNDEBUG /D_MBCS',
       '// 2008-06 native (inactive, GENERATED by work/donorfree-route/gen_sp_members.py): ServiceProvider::find<T>() const / create<T>() const',
       '// instances the donor-free boot reaches (bodies as AppUnit448_2008Services.cpp). Regenerate after new stubs appear.',
       '#include <boost/thread/once.hpp>', '#include "v8tree/Service.h"'] + ['#include "%s"' % i for i in sorted(inc)] + ['#include "util/Object.h"', '', 'namespace RBX', '{', defs, ''] + lines + ['}', '']
(ROOT / 'rebuild/2008-06/native-classes/ServiceProviderMembersBoot2008.cpp').write_text('\n'.join(src))
print(len(lines), 'instances; skipped (no header):', skipped)
