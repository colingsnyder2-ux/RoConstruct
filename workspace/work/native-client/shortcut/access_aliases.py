"""2007 engine headers and 2008 code disagree on member access (public/protected/private), which changes the MSVC mangling
(QAE/IAE/AAE, UAE/MAE/EAE, SA/KA/CA) of the very same function.  For every symbol the stub-backed link leaves undefined, look for
a definition that differs only in that access letter and emit /alternatename aliases into AccessAliasGlue.cpp.
python access_aliases.py [chosen.json]   (reads shortcut/unresolved12.json and the engine + chosen objects)"""
import json, re, sys
from pathlib import Path
sys.path.insert(0, '.')
from roc.rebuild import coff_externals
H = Path('work/native-client/shortcut')
un = json.load(open(H / 'unresolved12.json'))
chosen = json.load(open(H / (sys.argv[1] if len(sys.argv) > 1 else 'chosen_verbs.json')))
objs = list(Path('rebuild/2008-06/out/RbxgsApp/linked').glob('*.obj')) + [Path(c) for c in chosen if Path(c).exists()] + \
    list(Path('work/native-client/obj-engine-abi').glob('*.obj'))
defined = set()
for o in objs:
    defined |= {s for s, d in coff_externals(o.read_bytes()).items() if d}
GROUPS = ['AIQ', 'EMU', 'CKS']
# member function decoration: ...@@<access><cv/this>...  e.g. ??0X@RBX@@IAE@..., ?f@X@RBX@@UAEXXZ, ?g@X@@SAXXZ
pat = re.compile(r'^(\?[^@]*(?:@[^@]+)*@@)([A-Z])([A-Z].*)$')
lines, n = [], 0
for s in un:
    m = pat.match(s)
    if not m:
        continue
    head, acc, tail = m.groups()
    grp = next((g for g in GROUPS if acc in g), None)
    if not grp:
        continue
    for alt in grp:
        if alt == acc:
            continue
        cand = head + alt + tail
        if cand in defined:
            lines.append('#pragma comment(linker, "/alternatename:%s=%s")' % (s, cand)); n += 1
            break
src = ['// Shortcut glue (owner-authorized), generated by access_aliases.py: the same member under the 2007 engine access mangling.'] + lines
(H / 'AccessAliasGlue.cpp').write_text('\n'.join(src) + '\n')
print('aliases', n, 'of', len(un), 'unresolved')
