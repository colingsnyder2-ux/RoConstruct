"""Build FOR_REVIEW.md: blocked items that need only a quick human/agent look.

Read-only aggregation of existing receipts (missing inputs are skipped).
Ordered by payoff per minute of review.  Regenerate any time:

    python work/native-client/native_review_queue.py
"""
import json
import re
from collections import Counter, defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]


def load(path):
    try:
        return json.loads(Path(path).read_text(encoding='utf-8'))
    except (OSError, ValueError):
        return None


def first_error(result_path):
    folder = (ROOT / result_path).parent
    for log in sorted(folder.rglob('compile.log')) + sorted(folder.parent.glob(folder.name + '*/**/compile.log')):
        for line in log.read_text(encoding='utf-8', errors='replace').splitlines():
            hit = re.search(r'([\w.]+)\((\d+)\) : (?:fatal )?error (C\d+): (.*)', line)
            if hit:
                return {'file': hit[1], 'line': int(hit[2]), 'code': hit[3], 'text': hit[4][:160], 'log': log.relative_to(ROOT).as_posix()}
    return None


CLASS_AT = {}


def suggest(err):
    """Where the missing thing lives, if one place in the repo provides it."""
    if not err:
        return ''
    if not CLASS_AT:
        pat = re.compile(r'^[ 	]*(?:class|struct)[ 	]+(?:\w+[ 	]+)?([A-Za-z_]\w*)[ 	]*(?::[^;{]*)?\{', re.M)
        for root in (ROOT / 'rebuild/2008-06/native-headers', ROOT / 'tools'):
            for path in root.rglob('*.h'):
                try:
                    text = path.read_text(encoding='utf-8', errors='replace')
                except OSError:
                    continue
                CLASS_AT.setdefault('file:' + path.name, []).append(path)
                for name in set(pat.findall(text)):
                    CLASS_AT.setdefault(name, []).append(path)
    hit = re.search(r"include file: '([^']+)'", err['text'])
    if hit:
        found = CLASS_AT.get('file:' + hit[1].split('/')[-1], [])
        return 'add /I ' + '; '.join(sorted({p.parent.relative_to(ROOT).as_posix() for p in found})[:3]) if found else 'file not in repo'
    hit = re.search(r"undefined (?:type|class) '([^']+)'", err['text'])
    if hit:
        found = CLASS_AT.get(hit[1].split('::')[-1], [])
        native = [p for p in found if 'native-headers' in p.as_posix()] or found
        return '#include ' + '; '.join(p.relative_to(ROOT).as_posix() for p in native[:2]) if native else 'no definition in repo'
    return ''


def main():
    md, data = ['# For review (generated by native_review_queue.py; do not hand-edit)', '',
                'Blocked items where a short look and one fix should be enough. Evidence paths are relative to the repo root.', ''], {}

    # 1. Ready to apply: proven template lines.
    promos = []
    for path in sorted(HERE.glob('claude-template-promote/*/promotion.json')):
        p = load(path)
        if p and p.get('promotable'):
            promos.append({'source': p['source'], 'lines': p['kept_lines'], 'addresses': p['new_exact_addresses'],
                           'apply': path.with_name('promotion.lines.txt').relative_to(ROOT).as_posix()})
    promos.sort(key=lambda r: -r['addresses'])
    seen, fresh = set(load(HERE / 'claude-template-applied.json') or {}), []  # already applied lines
    for p in promos:  # same line passes in many TUs: credit each line to its first (largest) source
        lines = set((ROOT / p['apply']).read_text(encoding='utf-8').split('\n')) - {''}
        new = lines - seen
        seen |= lines
        if new:
            fresh.append(dict(p, lines_not_in_earlier_source=len(new)))
    data['template_promotions'] = fresh
    md += ['## 1. Ready to apply: proven template lines (%d sources)' % len(fresh),
           'Review: none needed beyond lease + your full-TU check. Fix: append the file under `apply` to the source.',
           'Add each line in one source only. Sorted by new exact addresses.', '',
           '| source | lines (new vs earlier rows) | new exact addresses | apply |', '|---|---|---|---|']
    md += ['| %s | %d (%d) | %d | `%s` |' % (p['source'].split('/')[-1], p['lines'], p['lines_not_in_earlier_source'],
                                            p['addresses'], p['apply']) for p in fresh[:40]]
    md.append('')

    # 2. One fix clears many: wrong header provider.
    differs = load(HERE / 'claude-vftable-differs.json') or []
    real = [d for d in differs if 'error C' not in d['declared'] and 'Unknown compiler' not in d['declared']]
    data['vftable_differs'] = real
    md += ['## 2. One fix clears many: header virtual order contradicts the image (%d slots)' % len(real),
           'Review: which header defines the class in these sources. Fix: include order / provider.', '',
           '| vftable | slot | header says | image has | sources |', '|---|---|---|---|---|']
    md += ['| `%s` | %d | %s | %s | %d |' % (d['vftable'], d['slot'], d['declared'], ', '.join(d['image']), len(d['sources']))
           for d in real]
    md.append('')
    layout = defaultdict(lambda: {'sources': set(), 'checks': set()})
    for path in HERE.glob('layout-sweep/*.gate.json'):
        g = load(path)
        for c in (g or {}).get('classes', []):
            bad = [(k['offset'], k['proof']) for k in c['checks'] if k['verdict'] == 'differ']
            if bad:
                layout[c['class']]['sources'].add(path.name[:-10])
                layout[c['class']]['checks'].update(bad)
    conflicts = {c['class']: c for c in load(HERE / 'claude-header-provider-conflicts.json') or []}
    rows = sorted(layout.items(), key=lambda kv: -len(kv[1]['sources']))
    data['layout_differs'] = [{'class': c, 'sources': sorted(v['sources']), 'checks': sorted(v['checks']),
                               'two_providers': conflicts.get(c.split('::')[-1])} for c, v in rows]
    md += ['## 3. Class layout contradicts the image (%d classes)' % len(rows),
           'Review: the listed offsets against the header that wins in those sources. "two providers" = class is defined in both native-headers and rbxgs App include (likely wrong provider).', '',
           '| class | sources | two providers | first differing offsets |', '|---|---|---|---|']
    md += ['| %s | %d | %s | %s |' % (c, len(v['sources']), 'yes' if c.split('::')[-1] in conflicts else 'no',
                                     '; '.join('%d %s' % k for k in sorted(v['checks'])[:3])) for c, v in rows[:40]]
    md.append('')

    # 4/5. Codex attempts that failed to compile or compiled non-exact.
    reports = sorted(HERE.glob('codex-native-recovery-report-v*.json'), key=lambda p: p.stat().st_mtime)
    report = load(reports[-1]) if reports else None
    attempted = ((report or {}).get('blocked', {}).get('attempted', {}) or {}).get('rows', {})
    groups, drafts = defaultdict(list), []
    for addr, row in attempted.items():
        if row['status'] == 'compile_failed':
            err = first_error(row['result'])
            key = '%s %s' % (err['code'], err['text']) if err else 'no compile.log error found'
            groups[key].append({'addr': addr, 'symbol': row['symbol'], 'owner': row['owner'], 'error': err})
        elif row['status'] in ('draft', 'symbol_not_emitted', 'missing'):
            drafts.append({'addr': addr, 'status': row['status'], 'symbol': row['symbol'], 'owner': row['owner'], 'result': row['result']})
    data['compile_failed'] = groups
    md += ['## 4. Convert attempts that fail to compile (%d addresses, %d distinct first errors)'
           % (sum(map(len, groups.values())), len(groups)),
           'Review: the first error only. One fix usually clears every address in the group. Source: `%s`.' % (reports[-1].name if reports else 'no report'), '',
           '| first error | addresses | owners | suggested fix | log |', '|---|---|---|---|---|']
    for key, rows_ in sorted(groups.items(), key=lambda kv: -len(kv[1])):
        err = rows_[0]['error']
        md.append('| %s | %d | %s | %s | `%s:%s` |' % (key.replace('|', '/'), len(rows_), ', '.join(sorted({r['owner'] for r in rows_}))[:60], suggest(err),
                                                 err['log'] if err else '-', err['line'] if err else '-'))
    md.append('')
    data['not_exact'] = drafts
    md += ['## 5. Compiled but not exact / symbol missing (%d addresses)' % len(drafts),
           'Review: `roc.cmd native-asm 2008-06 ADDR --obj ...` diff; often flags (`/fp:fast`, `/O2` vs `/Ox`) or one declaration.', '',
           '| address | status | owner | symbol | result |', '|---|---|---|---|---|']
    md += ['| %s | %s | %s | `%s` | `%s` |' % (d['addr'], d['status'], d['owner'], d['symbol'][:70], d['result']) for d in drafts[:60]]
    md.append('')

    # 5b. Native sources that do not compile unchanged (template gate baseline).
    failures = load(HERE / 'claude-baseline-compile-failures.json') or {}
    data['native_sources_not_compiling'] = failures
    md += ['## 5b. Native sources that do not compile unchanged (%d sources, %d distinct first errors)'
           % (sum(map(len, failures.values())), len(failures)),
           'Review: first error only. Known: `get_thread_name` is declared only in `work/upstream/OpenRBX/Client/App/include/util/boost.hpp`; these sources get rbxgs `util/boost.hpp` (provider choice).', '',
           '| first error | sources | in file | example |', '|---|---|---|---|']
    for key, items in sorted(failures.items(), key=lambda kv: -len(kv[1])):
        md.append('| %s | %d | %s | %s: %s |' % (key.replace('|', '/'), len(items), ', '.join(sorted({i['file'] or '-' for i in items}))[:50],
                                              items[0]['source'], (items[0]['text'] or '')[:90].replace('|', '/')))
    md.append('')

    # 6. Lopsided closure conflicts.
    closure = load(HERE / 'claude-identity-closure.json') or {}
    lop = []
    for symbol, c in closure.get('conflicts', {}).items():
        votes = sorted(c['votes'].items(), key=lambda kv: -kv[1])
        if len(votes) == 2 and votes[0][1] >= 5 * votes[1][1] and votes[0][1] >= 5:
            lop.append({'symbol': symbol, 'likely': votes[0][0], 'votes': votes[0][1], 'other': votes[1][0], 'other_votes': votes[1][1]})
    lop.sort(key=lambda r: -r['votes'])
    data['lopsided_conflicts'] = lop
    md += ['## 6. Identity conflicts with lopsided votes (%d of %d conflicts)' % (len(lop), len(closure.get('conflicts', {}))),
           'Review: is the minority address a second copy (duplicate constant / ICF / second library copy)? If yes both are valid and the symbol can be bound per site.', '',
           '| symbol | likely | votes | other | votes |', '|---|---|---|---|---|']
    md += ['| `%s` | %s | %d | %s | %d |' % (r['symbol'][:70], r['likely'], r['votes'], r['other'], r['other_votes']) for r in lop[:40]]
    md.append('')

    # 7. Unnamed functions with proven owner/signature or strong donor candidate.
    memfn = [f for f in (load(HERE / 'claude-memfn-args.json') or {}).get('functions', []) if not f['bound'] and f['consistent'] and f['owner']]
    donor = [f for f in (load(HERE / 'claude-donor-strings.json') or {}).get('functions', [])
             if f['verdict'] == 'new' and f['shared_unique_strings'] >= 2]
    data['unnamed_with_owner'], data['donor_candidates'] = memfn, donor
    md += ['## 7. Unnamed functions that only need a name decision',
           '%d have a call-site proven owner class + signature (`claude-memfn-args.json`); %d have a donor candidate with >= 2 unique shared strings (`claude-donor-strings.json`, 89%% precision, unproven).' % (len(memfn), len(donor)), '',
           '| address | owner / candidate | evidence |', '|---|---|---|']
    md += ['| %s | %s | `%s` |' % (f['address'], f['owner'], f['signatures'][0][:90]) for f in memfn[:25]]
    md += ['| %s | %s | donor, %d strings |' % (f['address'], f['candidate'][:80], f['shared_unique_strings']) for f in donor[:25]]
    md.append('')

    (HERE / 'FOR_REVIEW.md').write_text('\n'.join(md) + '\n', encoding='utf-8')
    (HERE / 'claude-review-queue.json').write_text(json.dumps(data, indent=1, default=list) + '\n', encoding='utf-8')
    print({k: (len(v) if hasattr(v, '__len__') else v) for k, v in data.items()})


if __name__ == '__main__':
    main()
