def counted_by(address):
    """Receipts that count the address: in their top-level exact_function_rows (or, without that key, anywhere)."""
    key = '%08x' % address
    out = []
    for n, t in OTHERS.items():
        if '"%s"' % key not in t:
            continue
        try:
            j = json.loads(t)
        except ValueError:
            out.append(n)
            continue
        rows = j.get('exact_function_rows') if isinstance(j, dict) else None
        if rows is None or key in rows:
            out.append(n)
    return sorted(out)


def coff_index(obj):
    raw = Path(obj).read_bytes()
    sections, symbols, definitions, _ = match._coff_data_index(raw)
    bodies = {n: (b, r) for n, b, r in match.coff_functions(raw)}
    return raw, sections, symbols, definitions, bodies


INDEX = {}


def verify_row(obj, address, name, own, record=True):
    if obj not in INDEX:
        INDEX[obj] = coff_index(obj)
    raw, sections, symbols, definitions, bodies = INDEX[obj]
    body, refs = bodies[name]
    target, target_refs, _ = match.target('2008-06', '%08x' % address)
    exact = match.exact_match(target, target_refs, body, refs)
    entry = {'address': '%08x' % address, 'symbol': name, 'size': len(body), 'target_size': len(target), 'exact': exact}
    if not exact:
        return entry, []
    start, section = definitions[name]
    table = sections[section]
    code = raw[table[4] + start:]
    verified, local, helpers = {}, set(), []
    for i in range(table[7]):
        offset, index, kind = struct.unpack_from('<IIH', raw, table[5] + 10 * i)
        offset -= start
        if not 0 <= offset < len(body):
            continue
        symbol = symbols[index][0]
        if kind == 20:
            value = (address + offset + 4 + struct.unpack_from('<i', target, offset)[0]) & 0xffffffff
        else:
            value = (struct.unpack_from('<I', target, offset)[0] - struct.unpack_from('<i', code, offset)[0]) & 0xffffffff
        if nb.LOCAL_EH.match(symbol):
            local.add(symbol)
            continue
        hit = original.imported(value)
        if hit is not None:
            assert hit[1] == nb.plain(symbol), (name, symbol, hex(value), hit)
            how = '%s!%s' % hit
        elif symbol.startswith('??_C@'):
            pos, at = definitions[symbol]
            literal = raw[sections[at][4] + pos:sections[at][4] + sections[at][3]].split(b'\0')[0] + b'\0'
            assert original.data(value, len(literal)) == literal, (name, symbol, hex(value))
            how = 'string %r' % literal[:-1].decode()
        elif symbol.startswith('__real@'):
            bits = int(symbol[7:], 16)
            width = 8 if len(symbol) - 7 > 8 else 4
            assert original.data(value, width) == bits.to_bytes(width, 'little'), (name, symbol, hex(value))
            how = 'float constant %s' % symbol[7:]
        elif symbol.startswith('??_7'):
            rtti, at = original.vtable_class(value)
            cls = symbol[4:symbol.index('@@6B') + 2]
            assert rtti == '.?AV' + cls, (name, symbol, hex(value), rtti)
            how = 'vtable RTTI %s offset %#x' % (rtti, at)
        elif symbol in own:
            assert own[symbol] == value, (name, symbol, hex(value), hex(own[symbol]))
            how = 'own row'
        elif symbol in DATA:
            assert DATA[symbol] == value, (name, symbol, hex(value), hex(DATA[symbol]))
            how = 'static (evidence checked below)'
        elif symbol in EXTERNAL and EXTERNAL[symbol] is not None:
            assert EXTERNAL[symbol] == value, (name, symbol, hex(value), hex(EXTERNAL[symbol]))
            how = 'external' + (' (evidence name)' if names.get(value, '') == symbol else '')
        elif symbol in bodies:
            helpers.append((value, symbol))
            how = 'template helper (body compared at the bound address)'
        else:
            UNBOUND.append("    %r: %#x,   # %s in %s" % (symbol, value, names.get(value, '')[:60], name[:60]))
            continue
        if record:
            prev = binding.setdefault(symbol, (value, name))
            assert prev[0] == value, ('inconsistent', symbol, hex(prev[0]), prev[1], hex(value), name)
        verified[symbol] = '%s (%s)' % (hex(value), how)
    entry.update({'verified_targets': verified, 'local': sorted(local)})
    return entry, helpers


def resolve(obj, rows):
    funcs = {n for n, _, _ in match.coff_functions(Path(obj).read_bytes())}
    out = []
    for address, key in rows:
        hits = [n for n in funcs if n == key]
        if DISCOVER and len(hits) != 1:
            print('UNRESOLVED', '%08x' % address, key, sorted(n for n in funcs if key.split('@')[0] in n)[:4])
            continue
        assert len(hits) == 1, ('%08x' % address, key)
        out.append((address, hits[0]))
    return out


