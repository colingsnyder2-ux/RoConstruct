# ---- structure: allocation sizes before the constructor calls, RTTI bases --------------------------------------------
def new_before(call_site, ctor, size):
    window = original.data(call_site - 0x60, 0x65)
    assert window[-5] == 0xe8 and call_site + 5 + struct.unpack_from('<i', window, 0x61)[0] == ctor, hex(call_site)
    push = (b'\x6a' + bytes([size])) if size < 0x80 else (b'\x68' + struct.pack('<I', size))
    # the last `push size` before the constructor call, then the first `call operator new` after it (the operand
    # loads in between are scheduled by the compiler: PartDragTool() 00665f8f pushes 0x70 before the hitWorld copy)
    at = window.rindex(push)
    calls = [i for i in range(at + len(push), len(window) - 9)
             if window[i] == 0xe8 and call_site - 0x60 + i + 5 + struct.unpack_from('<i', window, i + 1)[0] == 0x6a0920]
    assert calls, hex(call_site)
    return '%08x: new(%#x) before %08x' % (call_site, size, ctor)


