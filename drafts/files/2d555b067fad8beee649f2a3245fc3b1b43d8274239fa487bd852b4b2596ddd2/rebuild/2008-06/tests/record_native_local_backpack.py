"""Verify the inactive native RBX::LocalBackpack / RBX::LocalBackpackItem recovery (2008-06).

Builds (document-swap flags, VS2008 RTM 21022, native headers only):
  * tests/NativeLocalBackpackLayout.cpp   layout probes (mov eax, imm32; ret) against allocation sizes and constructor
                                          stores;
  * native-classes/LocalBackpack2008.cpp  the original LocalBackpack unit 005fb710..005fd330 (bounded by Kernel
                                          005fb650 and Tool 005fd3a0), header native-headers/LocalBackpack2008/
                                          LocalBackpack2008.h (own path: shadows no donor header).

Rows are found by closure from seeds (the two constructors named by the factories that allocate the objects, and the
evidence-named entry points DataModel calls): every REL32/DIR32 relocation of an exact row is bound to the address the
original instruction uses. A target defined in the compiled object becomes a row at that address; a vtable target is
checked by original RTTI (class name and subobject offset) and walked slot by slot (the object is built from current
headers only), each slot symbol bound to the original slot value. Every other target is verified: imports by DLL
export name, string literals and class-name arrays by bytes, type descriptors by RTTI name, external functions by the
evidence name or the EXTERNAL map (call sites read in the original disassembly). A symbol binds to one address.
Rows outside the unit range count only when they are LocalBackpack / LocalBackpackItem template instances (class-name
template argument); other exact rows (ICF-shared inline bodies, Notifier templates) are support rows, not counted, and
rows another receipt counts are never counted here.
Writes work/2008-06/shared-layouts/local-backpack-working.json.
"""
