def resolve(obj, rows):
    funcs = [n for n, _, _ in match.coff_functions(Path(obj).read_bytes())]
    out = []
    for address, key in rows:
        hits = [n for n in funcs if n == key] or [n for n in funcs if n.startswith(key) and not nb.LOCAL_EH.match(n)]
        if DISCOVER and len(hits) != 1:
            print('UNRESOLVED', '%08x' % address, key[:120], [h[:120] for h in hits][:5])
            continue
        assert len(hits) == 1, ('%08x' % address, key, hits[:5])
        out.append((address, hits[0]))
    return out


def verify(build_key, rows, own, strict=True, record=True):
    raw = Path(OBJ[build_key]).read_bytes()
    sections, symbols, definitions, _ = match._coff_data_index(raw)
    bodies = {n: (b, r) for n, b, r in match.coff_functions(raw)}
    out = []
    for address, name in rows:
        body, refs = bodies[name]
        target, target_refs = target_of(address)
        exact = len(body) == len(target) and bool(match.exact_match(target, target_refs, body, refs))
        row = {'address': '%08x' % address, 'symbol': name, 'size': len(body), 'target_size': len(target),
               'exact': exact, 'build': build_key}
        out.append(row)
        if not exact:
            assert not strict or DISCOVER, (build_key, row['address'], name[:80], len(body), len(target))
            continue
        row.update({'verified_targets': {}, 'local_eh': []})
        start, section = definitions[name]
        table = sections[section]
        code = raw[table[4] + start:]
        for i in range(table[7]):
            offset, index, kind = struct.unpack_from('<IIH', raw, table[5] + 10 * i)
            offset -= start
            if not 0 <= offset < len(body):
                continue
            symbol = symbols[index][0]
            if kind == 20:
                value = (address + offset + 4 + struct.unpack_from('<i', target, offset)[0]) & 0xffffffff
            else:
                value = (struct.unpack_from('<I', target, offset)[0] - struct.unpack_from('<i', code, offset)[0]) & 0xffffffff
            where = '%08x+%#x' % (address, offset)
            if nb.LOCAL_EH.match(symbol):
                row['local_eh'].append(symbol)
                continue
            how = None
            hit = original.imported(value)
            if hit is not None:
                assert hit[1] == nb.plain(symbol), (where, symbol, hex(value), hit)
                how = '%s!%s' % hit
            elif symbol in own:
                assert own[symbol] == value, (where, symbol, hex(value), hex(own[symbol]))
                how = 'own row'
            elif symbol in ALIAS:
                assert symbol not in bodies and own[ALIAS[symbol]] == value, (where, symbol, hex(value))
                how = 'own row %s (alias: no vector deleting destructor is emitted)' % ALIAS[symbol]
            elif symbol in ACCESS_EXTERNAL:
                expect, evidence = ACCESS_EXTERNAL[symbol]
                assert expect == value and names.get(value) == evidence, (where, symbol, hex(value), names.get(value))
                how = 'external (evidence name %s; access letter differs)' % evidence
            elif symbol.startswith('??_C@'):
                lit = string_literal(raw, sections, definitions, symbol)
                assert original.data(value, len(lit)) == lit, (where, symbol, hex(value), lit)
                how = 'string literal %r' % lit[:-1].decode('latin-1')
            elif symbol.startswith('??_R0') and symbol.endswith('@8'):
                rtti = original.string(value + 8)
                assert norm(rtti) == norm('.' + symbol[5:-2]), (where, symbol, hex(value), rtti)
                how = 'RTTI %s' % rtti
            elif symbol.startswith('??_7'):
                rtti, at = original.vtable_class(value)
                cls = symbol[4:symbol.index('@@6B') + 2]
                assert norm(rtti) == norm('.?AV' + cls), (where, symbol, hex(value), rtti)
                how = 'vtable RTTI %s offset %#x' % (rtti, at)
            elif symbol in CLASS_NAMES:
                assert original.string(value) == CLASS_NAMES[symbol], (where, symbol, hex(value))
                how = 'class-name array %r' % CLASS_NAMES[symbol]
            elif symbol in EXTERNAL:
                assert EXTERNAL[symbol] == value, (where, symbol, hex(value), hex(EXTERNAL[symbol]))
                if norm(names.get(value, '')) == norm(symbol):
                    how = 'external (evidence name)'
                else:
                    if symbol not in IDENTITY:
                        assert DISCOVER, (where, symbol, names.get(value, '')[:100])
                        UNBOUND.append('    IDENTITY needed %r %#x # %s' % (symbol, value, names.get(value, '')[:70]))
                        continue
                    how = 'external (identity: %s)' % IDENTITY[symbol]
            elif symbol in LOCAL_STATIC_AT:
                assert LOCAL_STATIC_AT[symbol] == value, (where, symbol, hex(value), hex(LOCAL_STATIC_AT[symbol]))
                assert any(lo <= value < hi for lo, hi in DATA_SECTIONS), (where, symbol, hex(value))
                how = 'unit / function static (one address per symbol)'
            elif '%08x' % value in elsewhere and symbol in bodies:
                hb, hr = bodies[symbol]
                ht, htr = target_of(value)
                assert match.exact_match(ht, htr, hb, hr), ('counted-elsewhere body not exact', symbol, hex(value))
                how = 'row counted by %s (compiled body exact at the bound address)' % ', '.join(
                    sorted(set(elsewhere['%08x' % value])))
            elif symbol in bodies and value in FUNCTIONS:
                hb, hr = bodies[symbol]
                ht, htr = target_of(value)
                if len(hb) == len(ht) and match.exact_match(ht, htr, hb, hr):
                    HELPERS.setdefault(symbol, '%#x' % value)
                    how = 'helper body exact at the bound address (not counted here)'
            if how is None and names.get(value) and norm(names[value]) == norm(symbol):
                how = 'external (evidence name)'
            if how is None:
                UNBOUND.append("    %r: %#x,   # %s at %s" % (symbol, value, names.get(value, '')[:70], where))
                continue
            if record:
                bind(symbol, value, where)
            row['verified_targets'][symbol] = '%#x (%s)' % (value, how)
    return out


