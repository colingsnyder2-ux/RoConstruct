# ---- vtables from the object built with the current headers, slot by slot ---------------------------------------------
def compiled_vtable(obj, symbol):
    raw = Path(obj).read_bytes()
    sections, symbols, definitions, _ = match._coff_data_index(raw)
    start, section = definitions[symbol]
    table = sections[section]
    slots = {}
    for i in range(table[7]):
        offset, index, kind = struct.unpack_from('<IIH', raw, table[5] + 10 * i)
        if offset >= start:
            slots[(offset - start) // 4] = symbols[index][0]
    return [slots[i] for i in range(len(slots))]


def check_vtable(obj, symbol, address, known=None):
    known = known or {}
    out, bad = [], []
    for i, slot in enumerate(compiled_vtable(obj, symbol)):
        value = d(address + 4 * i)
        if slot.startswith('??_E') and '??_G' + slot[4:] in own:
            ok, how = own['??_G' + slot[4:]] == value, 'bound (??_G row)'
        elif slot in own:
            ok, how = own[slot] == value, 'bound'
        elif slot in EXTERNAL:
            ok, how = EXTERNAL[slot] == value, 'external'
            USED_EXTERNAL.add(slot)
        elif slot in pending_own:
            ok, how = pending_own[slot] == value, 'bound (pending-build-only row)'
        elif slot in FOLDED:
            ok, how = FOLDED[slot][0] == value, 'helper body'
        else:
            ok, how = False, 'unbound'
        if not ok and i in known:
            how = 'known mismatch: ' + known[i]
            ok = None
        out.append({'slot': i, 'symbol': slot, 'original': hex(value), 'ok': ok, 'how': how})
        if ok is False:
            bad.append((i, slot, hex(value), how))
    assert not bad or DISCOVER, (symbol, bad)
    if DISCOVER and bad:
        print('VTABLE', symbol[:60], bad)
    return out


