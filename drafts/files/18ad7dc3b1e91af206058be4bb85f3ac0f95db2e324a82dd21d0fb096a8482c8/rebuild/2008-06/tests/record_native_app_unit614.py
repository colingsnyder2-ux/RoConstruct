def compiled_vtable(obj, symbol):
    raw = Path(obj).read_bytes()
    sections, symbols, definitions, _ = match._coff_data_index(raw)
    start, section = definitions[symbol]
    table = sections[section]
    slots = {}
    for i in range(table[7]):
        offset, index, kind = struct.unpack_from('<IIH', raw, table[5] + 10 * i)
        if offset >= start:
            slots[(offset - start) // 4] = symbols[index][0]
    return [slots[i] for i in range(len(slots))]


def check_vtable(key, symbol, address):
    out, bad = [], []
    for i, slot in enumerate(compiled_vtable(OBJ[key], symbol)):
        value = d(address + 4 * i)
        hit = original.imported(value)
        if slot.startswith('??_E') and '??_G' + slot[4:] in slot_names:
            ok, how = slot_names['??_G' + slot[4:]] == value, 'bound (??_G row)'
        elif slot in slot_names:
            ok, how = slot_names[slot] == value, 'bound'
        elif hit is not None:
            ok, how = hit[1] == nb.plain(slot), 'import thunk %s!%s' % hit
        elif names.get(value, '') == slot:
            ok, how = True, 'evidence name at the slot target'
        elif slot in BODIES[key] and value in FUNCTIONS and match.exact_match(*target_of(value), *BODIES[key][slot]):
            # header-inline virtuals (`return this;`, `return NULL;`, empty bodies): identical-code folded elsewhere
            ok, how = True, 'compiled body exact at the slot target (identical-code folded)'
        else:
            ok, how = False, 'unbound'
        out.append({'slot': i, 'symbol': slot, 'original': hex(value), 'ok': ok, 'how': how})
        if not ok:
            bad.append((i, slot, hex(value), how, names.get(value, '')[:80]))
    assert not bad or DISCOVER, (symbol, bad)
    if bad:
        print('VTABLE', symbol[:60], bad)
    return out


