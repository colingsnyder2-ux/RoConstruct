def concatenated_target(parts):
    data, relocs, start = b'', [], parts[0]
    for a in parts:
        body, refs = target_of(a)
        assert start + len(data) == a, ('rows not contiguous', hex(a))
        relocs += [r + len(data) for r in refs]
        data += body
    return data, relocs


