def probe_slots(vt_symbol):
    start, sec = LDEF[vt_symbol]
    table = LSEC[sec]
    slots = {}
    for i in range(table[7]):
        off, idx, kind = struct.unpack_from('<IIH', LRAW, table[5] + 10 * i)
