def resolve(which, address, prefixes, need_exact=True):
    bodies = IMG[which][4]

    def ok(n, p):
        head, _, part = p.partition('|')
        return n.startswith(head) and part in n
    cands = [n for n in bodies if any(ok(n, p) for p in prefixes)]
    good = [n for n in cands if exact_at(which, n, address)] if need_exact else cands
    if len(good) != 1:
        if DISCOVER:
            print('UNRESOLVED', hex(address), prefixes[0][:80], [c[:80] for c in cands][:4], len(good))
            return None
        raise AssertionError(('row', hex(address), prefixes[0][:80], cands[:6], good))
    return good[0]


