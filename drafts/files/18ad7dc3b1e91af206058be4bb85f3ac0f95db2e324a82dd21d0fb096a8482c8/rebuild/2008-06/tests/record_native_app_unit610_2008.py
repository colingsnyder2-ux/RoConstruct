# ---- structure: allocation sizes before the constructor calls, RTTI bases --------------------------------------------
def new_then_ctor(at, size, ctor=None):
    """`push size; ... call operator new 006a0920` at `at`, optionally followed by the constructor call."""
    push = (b'\x6a' + bytes([size])) if size < 0x80 else (b'\x68' + struct.pack('<I', size))
    code = original.data(at, 0x40)
    assert code.startswith(push), (hex(at), code[:8].hex())
    calls = [at + i for i in range(len(code) - 5) if code[i] == 0xe8]
    targets = [(c, (c + 5 + struct.unpack('<i', original.data(c + 1, 4))[0]) & 0xffffffff) for c in calls]
    assert targets[0][1] == 0x6a0920, (hex(at), [hex(t) for _, t in targets])
    if ctor is not None:
        assert any(t == ctor for _, t in targets[1:]), (hex(at), hex(ctor))
    return '%08x: new(%#x)%s' % (at, size, (' before %08x' % ctor) if ctor else ' (constructor inlined)')


