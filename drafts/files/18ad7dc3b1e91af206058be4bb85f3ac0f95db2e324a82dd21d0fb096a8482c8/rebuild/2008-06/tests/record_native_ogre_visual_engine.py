def probes(obj, table):
    raw = Path(obj).read_bytes()
    found = {}
    for fn, size in table.items():
        name_, body_, _ = next(x for x in match.coff_functions(raw) if x[0].startswith('?nativeOgreVisualEngine_' + fn + '@@'))
        want = b'\x33\xc0\xc3' if size == 0 else b'\xb8' + struct.pack('<I', size) + b'\xc3'   # xor eax, eax for 0
        assert body_ == want, (fn, body_.hex())
        found[fn] = hex(size)
    return found


