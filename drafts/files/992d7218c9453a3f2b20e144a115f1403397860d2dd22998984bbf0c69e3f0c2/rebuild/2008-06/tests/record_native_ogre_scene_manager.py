# ---- verify (closure over own call/data targets) ------------------------------------------------------------------


def literal_ok(key, symbol, value):
    sections, symbols, definitions, _ = index[key]
    raw_ = objects[key]
    pos, at = definitions[symbol]
    data = raw_[sections[at][4] + pos:sections[at][4] + sections[at][3]]
    return original.data(value, len(data)) == data


def data_ok(key, symbol, value):
    sections, symbols, definitions, _ = index[key]
    raw_ = objects[key]
    pos, at = definitions[symbol]
    if sections[at][4] == 0:     # uninitialized
        return False
    data = raw_[sections[at][4] + pos:sections[at][4] + sections[at][3]]
    return len(data) > 0 and original.data(value, len(data)) == data


def verify_row(key, name, address):
    b, r = bodies[key][name]
    if address not in FUNCTIONS:
        return {'address': '%08x' % address, 'symbol': name, 'size': len(b), 'exact': False,
                'reason': 'no recorded function starts at the bound address'}, []
    target, target_refs, _ = match.target('2008-06', '%08x' % address)
    exact = match.exact_match(target, target_refs, b, r)
    entry = {'address': '%08x' % address, 'symbol': name, 'size': len(b), 'target_size': len(target), 'exact': exact}
    if not exact:
        return entry, []
    sections, symbols, definitions, _ = index[key]
    raw_ = objects[key]
    start, section = definitions[name]
    table = sections[section]
    code = raw_[table[4] + start:]
    verified, local, new = {}, set(), []
    for i in range(table[7]):
        offset, sidx, kind = struct.unpack_from('<IIH', raw_, table[5] + 10 * i)
        offset -= start
        if not 0 <= offset < len(b):
            continue
        symbol = symbols[sidx][0]
        if kind == 20:
            value = (address + offset + 4 + struct.unpack_from('<i', target, offset)[0]) & 0xffffffff
        else:
            value = (struct.unpack_from('<I', target, offset)[0] - struct.unpack_from('<i', code, offset)[0]) & 0xffffffff
        if LOCAL_EH.match(symbol):
            local.add(symbol)
            continue
        hit = original.imported(value)
        if hit is not None:
            assert hit[1] == nb.plain(symbol), (name, symbol, hex(value), hit)
            how = '%s!%s' % hit
        elif symbol.startswith('__real@'):
            assert original.data(value, len(symbol[7:]) // 2) == bytes.fromhex(symbol[7:])[::-1], (name, symbol)
            how = 'constant'
        elif symbol.startswith('??_C@'):
            assert literal_ok(key, symbol, value), (name, symbol, hex(value))
            how = 'literal'
        elif symbol.startswith('??_R0') and symbol.endswith('@8'):
            rtti = original.string(value + 8)
            assert rtti == '.' + symbol[5:-2], (name, symbol, hex(value), rtti)
            how = 'type descriptor %s' % rtti
        elif symbol.startswith('??_7') or symbol.startswith('??_S'):
            rtti, at = original.vtable_class(value)
            assert rtti == '.?AV' + symbol[4:symbol.index('@@6B') + 2], (name, symbol, hex(value), rtti)
            how = 'vtable RTTI %s offset %#x' % (rtti, at)
        elif symbol.startswith('__TI'):
            how = 'throw info (checked below)'
            THROWINFO.setdefault(symbol, value)
        elif symbol in DATA:
            assert DATA[symbol] == value, (name, symbol, hex(value))
            how = 'data'
        elif symbol in EXTERNAL:
            assert EXTERNAL[symbol] == value, (name, symbol, hex(value), hex(EXTERNAL[symbol]))
            how = 'external'
        elif symbol in bodies[key]:
            how = 'own (call-site binding)'
            new.append((key, symbol, value))
        elif key == 'pending' and symbol in PENDING_EXTERNAL:
            assert PENDING_EXTERNAL[symbol] == value, (name, symbol, hex(value))
            how = 'pending external (call site)'
        elif ('@?1??' in symbol or symbol.startswith('?$S')) and TU_DATA[0] <= value < TU_DATA[1]:
            how = 'function-local static in the unit data block'
        elif symbol in index[key][2] and data_ok(key, symbol, value):
            how = 'initialized data (bytes compared)'
        else:
            UNBOUND.append("    %r: %#x,   # %s in %s" % (symbol, value, names.get(value, '')[:60], name[:60]))
            continue
        prev = binding.setdefault(symbol, (value, name))
        assert prev[0] == value, ('inconsistent', symbol, hex(prev[0]), prev[1], hex(value), name)
        verified[symbol] = '%s (%s)' % (hex(value), how)
    entry.update({'verified_targets': verified, 'local': sorted(local)})
    return entry, new


