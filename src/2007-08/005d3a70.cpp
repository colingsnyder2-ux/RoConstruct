	void Tool::moveAllToolsToBackpack(Network::Player* player)
	{
		if (player)
		{
			if (ModelInstance* character = player->getCharacter())
			{
				while (Tool* tool = character->findFirstChildOfType<Tool>())
				{
					tool->setParent(player->getPlayerBackpack());
				}
			}
		}
	}

