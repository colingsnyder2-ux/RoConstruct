	Tool::ToolState Tool::computeDesiredState(Instance* testParent)
	{
		Humanoid* humanoid = Humanoid::modelIsCharacter(testParent);
		if (!humanoid)
			return IN_WORKSPACE;

		if (!humanoid->getTorso())
			return IN_CHARACTER;

		if (!humanoid->findRightArm() || !humanoid->findRightShoulder())
			return HAS_TORSO;

		return EQUIPPED;
	}

