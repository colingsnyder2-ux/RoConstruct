def counted_elsewhere():
    out = {}
    for path in glob.glob(str(ROOT / 'work/2008-06/shared-layouts/*.json')):
        if Path(path).name == RECEIPT.name:
            continue
        try:
            data = json.loads(Path(path).read_text())
        except Exception:
            continue
        if not isinstance(data, dict):
            continue
        rows = []
        if 'exact_function_rows' in data:
            rows = data['exact_function_rows']
        elif isinstance(data.get('exact_addresses'), list):
            rows = data['exact_addresses']
        elif isinstance(data.get('exact_unique_addresses'), list):
            rows = data['exact_unique_addresses']
        else:
            def walk(o):
                if isinstance(o, list):
                    for e in o:
                        walk(e)
                elif isinstance(o, dict):
                    if 'address' in o and o.get('exact') is True:
                        rows.append(o['address'])
                    else:
                        for v in o.values():
                            walk(v)
            walk(data.get('methods', []))
        if isinstance(rows, dict):
            rows = list(rows)
        for r in rows:
            r = r.get('address', '') if isinstance(r, dict) else str(r)
            m = re.match(r'(?:0x)?([0-9a-fA-F]{6,8})', r)
            if m:
                out.setdefault('%08x' % int(m.group(1), 16), []).append(Path(path).name)
    return out


def create_weld_proof():
    """004b2620 has no evidence name: prove it is Creatable<Instance>::create<Weld> from its bytes."""
    body, _ = target_of(0x4b2620)
    assert b'\x68\x54\x01\x00\x00' in body, 'push 0x154 (allocation size)'
    calls = {(0x4b2620 + i + 5 + struct.unpack_from('<i', body, i + 1)[0]) & 0xffffffff
             for i in range(len(body) - 4) if body[i] == 0xe8}
    assert 0x5e4810 in calls, sorted(hex(c) for c in calls)
    ctor, _ = target_of(0x5e4810)
    assert b'\xc7\x06' + struct.pack('<I', 0x83f24c) in ctor, 'Weld() stores the primary vtable 0083f24c'
    rtti, at = original.vtable_class(0x83f24c)
    assert rtti == '.?AVWeld@RBX@@' and at == 0, (rtti, at)
    return ('004b2620 pushes the allocation size 0x154, calls 005e4810 and shared_ptr<Weld>(Weld*) 004b2570; 005e4810 '
            'stores the vtable 0083f24c at +0 (RTTI .?AVWeld@RBX@@, offset 0): Creatable<Instance>::create<Weld>')


