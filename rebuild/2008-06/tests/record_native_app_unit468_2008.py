def points_to(row, text):
    size = FUNCS[row]['size']
    body = original.data(row, size)
    want = text.encode('latin-1') + b'\0'
    for i in range(size - 3):
        v = struct.unpack_from('<I', body, i)[0]
        if 0x7c0000 <= v < 0x980000:
            try:
                if original.data(v, len(want)) == want:
                    return v
            except Exception:
                pass
    return None


