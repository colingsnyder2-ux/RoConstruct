ADDR = re.compile(r'^(?:0x)?([0-9a-fA-F]{6,8})$')


def counted_by_others():
    out = {}
    for path in sorted(glob.glob(str(ROOT / 'work/2008-06/shared-layouts/*.json'))):
        if Path(path).resolve() == RECEIPT.resolve():
            continue
        try:
            data = json.loads(Path(path).read_text())
        except Exception:
            continue
        if not isinstance(data, dict):
            continue
        found = set()

        def add(x):
            m = ADDR.match(str(x.get('address', x.get('addr', '')) if isinstance(x, dict) else x).strip())
            if m:
                found.add(int(m.group(1), 16))
        for key in ('exact_function_rows', 'exact_addresses', 'exact_unique_addresses'):
            if isinstance(data.get(key), (list, dict)):
                for r in data[key]:
                    add(r)
        if 'exact_function_rows' not in data:
            def walk(o):
                if isinstance(o, dict):
                    if o.get('exact') is True and ('address' in o or 'addr' in o):
                        add(o)
                    for v in o.values():
                        walk(v)
                elif isinstance(o, list):
                    for e in o:
                        walk(e)
            walk(data)
        for a in found:
            out.setdefault(a, []).append(Path(path).name)
    return out


