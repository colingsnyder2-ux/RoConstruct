VTABLES = {}


def compiled_vtable(obj, symbol):
    raw, sections, symbols, definitions, _ = INDEX[obj]
    start, section = definitions[symbol]
    table = sections[section]
    slots = {}
    for i in range(table[7]):
        offset, index, kind = struct.unpack_from('<IIH', raw, table[5] + 10 * i)
        if offset >= start:
            slots[(offset - start) // 4] = symbols[index][0]
    return [slots[i] for i in range(len(slots))]


for symbol, (value, _) in sorted(binding.items()):
    if not symbol.startswith('??_7'):
        continue
    slots = compiled_vtable(OBJ, symbol)
    assert len(slots) == 1 and slots[0].startswith('??_E'), (symbol, slots)
    deleting = '??_G' + slots[0][4:]
    assert deleting in INDEX[OBJ][4], deleting
    VTABLES[symbol] = {'address': '%08x' % value, 'slot0': '%08x' % d(value), 'symbol': deleting}
    queue.append((d(value), deleting))

# Template helpers reached from the rows (closure): exact helpers are derived rows; their own targets are verified too.
seen = set()
while queue:
    value, symbol = queue.pop(0)
    if symbol in seen:
        continue
    seen.add(symbol)
    entry, helpers = verify_row(OBJ, value, symbol, own, record=True)
    elsewhere = counted_elsewhere(value)
    entry['counted_elsewhere'] = elsewhere
    if entry['exact']:
        HELPERS.setdefault('%08x' % value, []).append(entry)
        queue += helpers
    else:
        # A helper whose compiled body is longer than the target extent: if the target bytes match the compiled prefix
        # and the image bytes after the extent match the compiled tail, the extent omits a trailing funclet (BOUNDS).
        body, refs = INDEX[OBJ][4][symbol]
        target, target_refs, _ = match.target('2008-06', '%08x' % value)
        if len(body) > len(target):
            prefix = match.exact_match(target, target_refs, body[:len(target)], [o for o in refs if o < len(target)])
            tail = original.data(value + len(target), len(body) - len(target))
            tail_ok = match.exact_match(tail, [o - len(target) for o in refs if o >= len(target)],
                                        body[len(target):], [o - len(target) for o in refs if o >= len(target)])
            if prefix and tail_ok:
                entry['bounds_evidence'] = ('compiled body equals the target through its %d-byte extent and the image '
                                            'bytes 0x%x..0x%x equal the compiled trailing catch funclet (delete node; '
                                            'rethrow), which only EH tables reference: the true extent is %d bytes'
                                            % (len(target), value + len(target), value + len(body), len(body)))
        NOT_EXACT_HELPERS.setdefault('%08x' % value, []).append(entry)

