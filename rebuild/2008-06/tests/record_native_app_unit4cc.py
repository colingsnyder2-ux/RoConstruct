def classify(symbol, value, raw, sections, definitions, where):
    hit = original.imported(value)
    if hit is not None:
        assert hit[1] == nb.plain(symbol), (where, symbol, hex(value), hit)
        return '%s!%s' % hit
    if symbol.startswith('??_C@'):
        pos, sec = definitions[symbol]
        literal = raw[sections[sec][4] + pos:sections[sec][4] + sections[sec][3]].split(b'\0')[0] + b'\0'
        assert original.data(value, len(literal)) == literal, (where, symbol, hex(value))
        return 'literal'
    m = re.match(r'__real@([0-9a-f]{8}|[0-9a-f]{16})$', symbol)
    if m:   # x87 constant: its bytes at the referenced address
        literal = bytes.fromhex(m.group(1))[::-1]
        assert original.data(value, len(literal)) == literal, (where, symbol, hex(value))
        return 'constant bytes equal'
    if symbol.startswith('?prime_list@') and 'next_prime@bucket_array_base@' in symbol:
        # bucket_array_base::prime_list (28 primes 53, 97, 193 ... 4294967291), the table the sender recorder binds
        primes = struct.unpack('<28I', original.data(value, 0x70))
        assert primes[:3] == (53, 97, 193) and primes[-1] == 4294967291, (where, hex(value))
        return 'prime table bytes'
    if symbol.startswith('??_7') and symbol.endswith('@@6B@'):
        rtti, at = original.vtable_class(value)
        assert rtti == '.?AV' + symbol[4:-3], (where, symbol, hex(value), rtti)
        return 'vtable RTTI %s offset %#x' % (rtti, at)
    if symbol == '__TI2?AVbad_alloc@std@@':
        # std::_Allocate's throw info: its catchable type array names bad_alloc then exception
        catchable = d(value + 12)
        names = [original.string(d(d(catchable + 4 + 4 * i) + 4) + 8) for i in range(d(catchable))]
        assert names == ['.?AVbad_alloc@std@@', '.?AVexception@std@@'], (where, hex(value), names)
        return 'throw info (catchable types %s)' % ', '.join(names)
    if symbol in own:
        assert own[symbol] == value, (where, symbol, hex(value), hex(own[symbol]))
        return 'own row'
    if symbol in EXTERNAL:
        assert EXTERNAL[symbol] == value, (where, symbol, hex(value), hex(EXTERNAL[symbol]))
        return 'external'
    if EVIDENCE.get('%08x' % value, {}).get('symbol') == symbol:
        return 'evidence name'
    return instance(symbol, value, where)


def instance(symbol, value, where):
    """A body this unit (or the sender-unit evidence build) emits, proven by its bytes at the called address and by
    its own targets. Never counted."""
    if symbol in INSTANCES:
        assert INSTANCES[symbol]['address'] == hex(value), (where, symbol, hex(value))
        return 'instance (%s)' % INSTANCES[symbol]['build']
    for obj in (unit_obj, evidence_obj):
        if symbol not in bodies_of(obj):
            continue
        body = bodies_of(obj)[symbol][0]
        target = original.data(value, len(body))
        refs = bodies_of(obj)[symbol][1]
        mask = {r + k for r in refs for k in range(4)}
        if any(body[i] != target[i] for i in range(len(body)) if i not in mask):
            continue
        build_name = 'unit build' if obj == unit_obj else 'sender-unit evidence build'
        INSTANCES[symbol] = {'address': hex(value), 'build': build_name}
        row = verify(obj, [((value, 0, len(body), 'raw'), symbol)], False)[0]
        listed = FUNCS.get(value, {}).get('size')
        row.update({'address': hex(value), 'build': build_name, 'listed_size': listed,
                    'status': 'instance: bytes equal at the called address (relocations masked) in the %s, every own '
                              'target verified; not counted here' % build_name})
        INSTANCES[symbol] = row
        return 'instance (%s)' % build_name
    raise AssertionError(('unbound target', where, symbol, hex(value)))


def verify(obj, specs, exact_flag):
    CURRENT.append(obj)
    try:
        raw = Path(obj).read_bytes()
        sections, symbols, definitions, _ = match._coff_data_index(raw)
        out = []
        for spec, name in specs:
            body, refs = bodies_of(obj)[name]
            address, lo, hi = spec[:3]
            body, refs = body[lo:hi], [r - lo for r in refs if lo <= r < hi]
            if spec[3:] == ('raw',):
                target, target_refs = original.data(address, len(body)), []
                mask = {r + k for r in refs for k in range(4)}
                assert all(body[i] == target[i] for i in range(len(body)) if i not in mask), (name, hex(address))
            else:
                target, target_refs, _ = match.target('2008-06', '%08x' % address)
                assert match.exact_match(target, target_refs, body, refs), (name, hex(address), len(body), len(target))
            start, section = definitions[name]
            start += lo
            table = sections[section]
            code = raw[table[4] + start:]
            verified, local = {}, set()
            for i in range(table[7]):
                offset, index, kind = struct.unpack_from('<IIH', raw, table[5] + 10 * i)
                offset -= start
                if not 0 <= offset < len(body):
                    continue
                symbol = symbols[index][0]
                if kind == 20:
                    value = (address + offset + 4 + struct.unpack_from('<i', target, offset)[0]) & 0xffffffff
                else:
                    value = (struct.unpack_from('<I', target, offset)[0]
                             - struct.unpack_from('<i', code, offset)[0]) & 0xffffffff
                if nb.LOCAL_EH.match(symbol):
                    local.add(symbol)
                    continue
                how = classify(symbol, value, raw, sections, definitions, name)
                prev = binding.setdefault(symbol, value)
                assert prev == value, ('inconsistent binding', symbol, hex(prev), hex(value))
                verified[symbol] = '%s (%s)' % (hex(value), how)
            whole = (lo, hi) == (0, len(bodies_of(obj)[name][0]))
            out.append({'address': '%08x' % address, 'symbol': name + ('' if whole else ' [%#x:%#x]' % (lo, hi)),
                        'size': len(body), 'exact': exact_flag, 'verified_targets': verified,
                        'local_eh': sorted(local)})
        return out
    finally:
        CURRENT.pop()


