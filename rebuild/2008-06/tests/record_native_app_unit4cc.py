def counted_elsewhere():
    out = {}
    for path in glob.glob(str(ROOT / 'work/2008-06/shared-layouts/*.json')):
        if Path(path).name == RECEIPT.name:
            continue
        try:
            data = json.loads(Path(path).read_text())
        except Exception:
            continue
        if not isinstance(data, dict):
            continue
        rows_ = []
        if isinstance(data.get('exact_function_rows'), (list, dict)):
            rows_ = list(data['exact_function_rows'])
        else:
            for key in ('exact_addresses', 'exact_unique_addresses', 'exact_distinct_addresses'):
                if isinstance(data.get(key), (list, dict)):
                    rows_ = list(data[key])
                    break
            else:
                def walk(o):
                    if isinstance(o, list):
                        for e in o:
                            walk(e)
                    elif isinstance(o, dict):
                        if 'address' in o and o.get('exact') is True:
                            rows_.append(o['address'])
                        else:
                            for v in o.values():
                                walk(v)
                walk(data.get('methods', []))
        for r in rows_:
            r = r.get('address', '') if isinstance(r, dict) else str(r)
            m = re.match(r'(?:0x)?([0-9a-fA-F]{6,8})$', r.strip())
            if m:
                out.setdefault(int(m.group(1), 16), set()).add(Path(path).name)
    return out


