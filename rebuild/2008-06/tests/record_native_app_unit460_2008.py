def target_of(address):
    body, refs, _ = match.target('2008-06', '%08x' % address)
    return body, refs


def try_fold(which, symbol, value):
    """A COMDAT body bound outside the counted rows: the body compiled here must be exact there."""
    if symbol not in BODIES[which] or value not in FUNCTIONS or FOLD_AT.get(symbol) != value:
        return False
    body, refs = BODIES[which][symbol]
    target, target_refs = target_of(value)
    if not match.exact_match(target, target_refs, body, refs):
        return False
    FOLDED.setdefault(symbol, (value, which))
    return FOLDED[symbol][0] == value


def resolve(rows, which):
    funcs = BODIES[which]
    for address, name in rows:
        assert name in funcs or DISCOVER, ('%08x' % address, name, [n for n in funcs if n[:20] == name[:20]])
    return [(a, n) for a, n in rows if n in funcs]


def bind_targets(which, name, address, target, own, record=True):
    raw = Path(OBJ[which]).read_bytes()
    sections, symbols, definitions, _ = match._coff_data_index(raw)
    body = BODIES[which][name][0]
    start, section = definitions[name]
    table = sections[section]
    code = raw[table[4] + start:]
    verified, local = {}, set()
    for i in range(table[7]):
        offset, index, kind = struct.unpack_from('<IIH', raw, table[5] + 10 * i)
        offset -= start
        if not 0 <= offset < len(body):
            continue
        symbol = symbols[index][0]
        if kind == 20:
            value = (address + offset + 4 + struct.unpack_from('<i', target, offset)[0]) & 0xffffffff
        else:
            value = (struct.unpack_from('<I', target, offset)[0] - struct.unpack_from('<i', code, offset)[0]) & 0xffffffff
        if nb.LOCAL_EH.match(symbol):
            local.add(symbol)
            continue
        hit = original.imported(value)
        if hit is not None:
            assert hit[1] == nb.plain(symbol), (name, symbol, hex(value), hit)
            how = '%s!%s' % hit
        elif symbol.startswith('??_7'):
            rtti, at = original.vtable_class(value)
            cls = symbol[4:symbol.index('@@6B') + 2]
            assert rtti == '.?AV' + cls, (name, symbol, hex(value), rtti)
            how = 'vtable RTTI %s offset %#x' % (rtti, at)
        elif symbol in own:
            assert own[symbol] == value, (name, symbol, hex(value), hex(own[symbol]))
            how = 'own row'
        elif symbol in EXTERNAL:
            assert EXTERNAL[symbol] == value, (name, symbol, hex(value), hex(EXTERNAL[symbol]))
            how = 'external' + (' (evidence name)' if names.get(value, '') == symbol else '')
            USED_EXTERNAL.add(symbol)
        elif try_fold(which, symbol, value):
            how = 'COMDAT body folded across instantiations, compared exact at the bound address'
        else:
            UNBOUND.append("    %r: %#x,   # %s in %s" % (symbol, value, names.get(value, '')[:60], name[:60]))
            continue
        if record:
            prev = binding.setdefault(symbol, (value, name))
            assert prev[0] == value, ('inconsistent', symbol, hex(prev[0]), prev[1], hex(value), name)
        verified[symbol] = '%s (%s)' % (hex(value), how)
    return verified, local


def verify(which, rows, own, record=True):
    result = []
    for address, name in rows:
        body, refs = BODIES[which][name]
        target, target_refs = target_of(address)
        exact = match.exact_match(target, target_refs, body, refs)
        entry = {'address': '%08x' % address, 'symbol': name, 'size': len(body), 'target_size': len(target),
                 'exact': exact}
        if not exact:
            assert DISCOVER, (name, entry['address'], len(body), len(target))
            result.append(entry)
            continue
        verified, local = bind_targets(which, name, address, target, own, record)
        entry.update({'verified_targets': verified, 'local_eh': sorted(local)})
        result.append(entry)
    return result


